#!/usr/bin/env python3
"""capture_assets.py — regenerate packages/gateway-core/src/core/assetTables.ts.

P3 (gateway manifest Phase 3, .scratch/gateway-ts-map.md): the 4 asset
READ doors are REAL byte/JSON serves in TS (doors/assets.ts), not
static captures — the bodies depend on the on-disk fixture tree.
What IS static is the CODE tables the port reads:

  - CONTENT_TYPES: ext -> wire content-type, probed by CALLING
    python/editor_runs.content_type_of (never hand-copied);
  - INPUT_EXTS: the uploads door's image allowlist
    (python/editor_runs._INPUT_IMAGE_EXTS);
  - MESH_EXTS / DOC_EXTS: python/asset_ledger's mesh/document vocab.

The media-kind ext sets (image/audio/video/model) are DATA, not
code: the TS door reads packages/web/dsh/media-plugin/media-kinds.json
at request time (repo-anchored, single source of truth) — baking them
here would teach a stale vocabulary the day an ext lands.

Usage:
  python3 packages/gateway/scripts/capture_assets.py          # regenerate
  python3 packages/gateway/scripts/capture_assets.py --check  # wall drift pin

Re-running is idempotent: identical py outputs -> identical file
(no timestamps in the emit).
"""

import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True

REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO / "python"))

import asset_ledger as _al  # noqa: E402  (MESH/DOC vocab source)
import editor_runs as _er  # noqa: E402  (content_type_of + input allowlist)

# Every ext the port may classify: the media-kind data sets + the
# mesh/doc code sets + the code-table extras content_type_of names
# explicitly (json/txt/md/yaml/html/svg/gif).
MEDIA_DOC = json.loads(
    (REPO / "packages" / "web" / "dsh" / "media-plugin"
     / "media-kinds.json").read_text(encoding="utf-8"))
_PROBE = sorted(
    {e.lower() for k in ("image", "audio", "video", "model")
     for e in MEDIA_DOC["kinds"][k]["exts"]}
    | {e.lower() for e in _al._MESH}
    | {e.lower() for e in _al._DOC}
    | {"json", "txt", "md", "yaml", "html", "svg", "gif"})

OUT = (REPO / "packages" / "gateway-core" / "src" / "core"
       / "assetTables.ts")


def _render() -> str:
    lines = [
        "// GENERATED by packages/gateway/scripts/capture_assets.py — DO NOT EDIT.",
        "// Regenerate: python3 packages/gateway/scripts/capture_assets.py",
        "// Source of truth (probed, never hand-copied):",
        "//   python/editor_runs.content_type_of  -> CONTENT_TYPES",
        "//   python/editor_runs._INPUT_IMAGE_EXTS -> INPUT_EXTS",
        "//   python/asset_ledger._MESH/_DOC      -> MESH_EXTS/DOC_EXTS",
        "// The media-kind ext sets stay DATA: doors/assets.ts reads",
        "// packages/web/dsh/media-plugin/media-kinds.json at request",
        "// time (repo-anchored). Unknown exts fall back to",
        "// application/octet-stream exactly as content_type_of does.",
        "//",
        "// Erasable-syntax TS only (node --experimental-strip-types):",
        "// plain constants, no enums.",
        "",
        "// ext (lowercase, no dot) -> wire content-type.",
        "export const CONTENT_TYPES: Record<string, string> = {",
    ]
    for ext in _PROBE:
        lines.append("  %s: %s," % (
            json.dumps(ext), json.dumps(_er.content_type_of("f." + ext))))
    lines += [
        "};",
        "",
        "// The inputs-door allowlist (ext -> content-type).",
        "export const INPUT_EXTS: Record<string, string> = {",
    ]
    for ext in sorted(_er._INPUT_IMAGE_EXTS):
        lines.append("  %s: %s," % (
            json.dumps(ext), json.dumps(_er._INPUT_IMAGE_EXTS[ext])))
    lines += [
        "};",
        "",
        "// Mesh / document extension vocab (asset_ledger kind_for).",
        "export const MESH_EXTS: readonly string[] = %s;"
        % json.dumps(sorted(_al._MESH)),
        "export const DOC_EXTS: readonly string[] = %s;"
        % json.dumps(sorted(_al._DOC)),
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = _render()
    if "--check" in argv:
        try:
            cur = OUT.read_text(encoding="utf-8")
        except OSError:
            cur = ""
        if cur != text:
            sys.stderr.write(
                "assetTables.ts is stale vs python/editor_runs + python/asset_ledger"
                " — run packages/gateway/scripts/capture_assets.py\n")
            return 1
        print("assetTables.ts fresh")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print("wrote %s (%d content-types, %d input exts)"
          % (OUT.relative_to(REPO), len(_PROBE), len(_er._INPUT_IMAGE_EXTS)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
