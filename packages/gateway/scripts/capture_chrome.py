#!/usr/bin/env python3
"""capture_chrome.py — regenerate packages/gateway-doors/src/doors/chrome.ts.

Phase 1 (gateway manifest .scratch/gateway-ts-map.md Phase 1): the
J1-J10 health/chrome doors as STATIC captured JSON. The bodies are
obtained by importing python/editor_runs (+ catalog, which the derived
doors ride) in python3 — NEVER hand-written — so the TS shell serves
the exact wire bytes the retired py oracle owned (frozen at capture —
the oracle died 2026-09-08, these bytes are the contract):

  python3 packages/gateway/scripts/capture_chrome.py

emits packages/gateway-doors/src/doors/chrome.ts with one raw-JSON string
constant per door (the exact json.dumps(payload, indent=2,
default=str) bytes _adapt would send) plus the CHROME_BODIES map.
Re-running is idempotent: identical py outputs -> identical file
(no timestamps in the emit). The TS side serves these strings
VERBATIM (no re-serialization): a parse+reserialize round-trip would
drift bytes (py ensure_ascii escapes non-ASCII as \\uXXXX while
JSON.stringify emits raw UTF-8; py float 1.0 vs JS number 1), so raw
is the only byte-faithful shape. See ctx.ts dispatch.
"""

import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True

REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO / "python"))

import catalog  # noqa: F401  (derived-door rail; import proves availability)
import editor_runs as _er

DOORS: tuple = (
    ("HEALTH", "/v1/health", _er.health),
    ("THEMES", "/v1/themes", _er.themes),
    ("TAGS", "/v1/tags", _er.tags),
    ("SERVICES", "/v1/services", _er.services),
    ("RIGHT_PANES", "/v1/right-panes", _er.right_panes),
    ("UI_SLOTS", "/v1/ui-slots", _er.ui_slots),
    ("TOOLS", "/v1/tools", _er.tools),
    ("SHELL", "/v1/shell", _er.shell),
    ("PLUGINS", "/v1/plugins", _er.plugins_registry),
    ("MODELS", "/v1/models", _er.models),
)

OUT = (REPO / "packages" / "gateway-doors" / "src" / "doors"
       / "chrome.ts")


def main() -> int:
    bodies: dict[str, str] = {}
    for _name, _path, fn in DOORS:
        bodies[_path] = json.dumps(fn(), indent=2, default=str)
    lines = [
        "// GENERATED by packages/gateway/scripts/capture_chrome.py — DO NOT EDIT.",
        "// Regenerate: python3 packages/gateway/scripts/capture_chrome.py",
        "// Source of truth: python/editor_runs.health/themes/tags/services/",
        "//   right_panes/ui_slots/tools/shell/plugins_registry/models",
        "//   (tools + ui_slots DERIVED — card classes / ui.yaml claims —",
        "//   via the catalog rail; the rest are chrome stubs). Each",
        "// constant holds the EXACT json.dumps(payload, indent=2,",
        "// default=str) bytes the retired py oracle's _adapt sent",
        "// (frozen at capture — the oracle died 2026-09-08, these",
        "// bytes are the contract); ctx.ts serves",
        "// them verbatim (parse+reserialize would drift: ensure_ascii",
        "// \\uXXXX vs raw UTF-8, float 1.0 vs number 1).",
        "//",
        "// Erasable-syntax TS only (node --experimental-strip-types):",
        "// plain string constants, no enums.",
        "",
    ]
    for name, path, _fn in DOORS:
        lines.append("// J door: GET %s" % path)
        lines.append("export const %s_JSON: string = %s;" % (
            name, json.dumps(bodies[path], ensure_ascii=False)))
        lines.append("")
    lines.append("// Path -> exact wire bytes (status 200, application/json).")
    lines.append("export const CHROME_BODIES: Record<string, string> = {")
    for name, path, _fn in DOORS:
        lines.append('  "%s": %s_JSON,' % (path, name))
    lines.append("};")
    lines.append("")
    lines.append("// The ten Phase-1 doors in J1-J10 order.")
    lines.append("export const CHROME_PATHS: readonly string[] = [")
    for _name, path, _fn in DOORS:
        lines.append('  "%s",' % path)
    lines.append("];")
    lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("wrote %s (%d doors)" % (OUT.relative_to(REPO), len(DOORS)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
