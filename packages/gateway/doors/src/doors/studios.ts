export class ArtifactRefError extends Error {}

const ASSET_RUNS_PREFIX = "/v1/assets/runs/";

/** os.path.join semantics (node's path.join does NOT reset on an
 *  absolute segment — py's does: join(out, "/etc/x") == "/etc/x",
 *  which is how the escapes leg reaches the containment guard). */
function posixJoin(base: string, seg: string): string {
  return seg.startsWith("/") ? seg : join(base, seg);
}

/** Longest-common-prefix of two absolute paths, component-wise
 *  (py os.path.commonpath equality — both inputs absolute here). */
function commonPrefix(a: string, b: string): string {
  const ac: string[] = a.split("/");
  const bc: string[] = b.split("/");
  const out: string[] = [];
  for (let i = 0; i < Math.min(ac.length, bc.length); i++) {
    if (ac[i] !== bc[i]) break;
    out.push(ac[i] as string);
  }
  return out.join("/") || "/";
}

function isFile(p: string): boolean {
  try {
    return statSync(p).isFile();
  } catch {
    return false;
  }
}

export function resolveArtifactFile(ref: string, outRoot: string): string {
  // infra/python/artifact_refs.py resolve_artifact_file — all FOUR ref forms,
  // verbatim messages, NO percent-decoding (ref values ride the
  // JSON body, never the URL path).
  const raw: string = (ref ?? "").trim();
  if (raw === "") {
    throw new ArtifactRefError("empty artifact ref (nothing to resolve)");
  }
  if (raw.includes("..")) {
    throw new ArtifactRefError(
      "artifact ref refuses traversal: " + pyReprString(raw),
    );
  }
  let cand: string;
  if (raw.startsWith(ASSET_RUNS_PREFIX)) {
    // form 2: the estate's artifact URL.
    const rel: string = raw.slice(ASSET_RUNS_PREFIX.length);
    if (rel === "" || rel.endsWith("/") || !rel.includes("/")) {
      throw new ArtifactRefError(
        "malformed artifact URL (want /v1/assets/runs/<run_id>/<file>): " +
          pyReprString(raw),
      );
    }
    cand = posixJoin(outRoot, rel);
  } else if (raw.includes("/") && !raw.startsWith("/")) {
    // form 3: runs-relative <run_id>/<file>.
    cand = posixJoin(outRoot, raw);
  } else if (raw.startsWith("/")) {
    // form 1: absolute disk path — verified as-is (no containment).
    cand = raw;
  } else {
    throw new ArtifactRefError(
      "artifact ref is a bare " + pyReprString(raw) +
        " — not an absolute path, an artifact URL " +
        "(/v1/assets/runs/<run>/<file>), or a runs-relative " +
        "<run>/<file> (a bare filename lives in the ComfyUI input " +
        "dir and is the caller's staging concern, never a disk lookup)",
    );
  }
  const absCand: string = resolve(cand);
  // The join must stay under the output root (both sides
  // abspath'd — py os.path.abspath each).
  if (commonPrefix(absCand, resolve(outRoot)) !== resolve(outRoot)) {
    throw new ArtifactRefError(
      "artifact ref escapes the output root: " + pyReprString(raw),
    );
  }
  if (!isFile(absCand)) {
    const run: string = raw.startsWith(ASSET_RUNS_PREFIX)
      ? (raw.slice(ASSET_RUNS_PREFIX.length).split("/", 1)[0] as string)
      : "?";
    throw new ArtifactRefError(
      "artifact not found on disk: " + pyReprString(raw) + " (looked up " +
        absCand + ") — the upstream run may have been pruned, or the ref was never an output of run " +
        run,
    );
  }
  return absCand;
}

