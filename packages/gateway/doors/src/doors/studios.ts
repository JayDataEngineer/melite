/** py subscript-with-KeyError/TypeError texts (the promotion reads
 *  doc["phenotype"] then doc["scale"] off the RAW parsed doc). */
function subscriptKey(
  doc: unknown,
  key: string,
): { value: unknown } | { error: string } {
  if (isPlainObject(doc)) {
    if (!(key in doc)) return { error: "'" + key + "'" };
    return { value: (doc as Record<string, unknown>)[key] };
  }
  if (Array.isArray(doc)) {
    return { error: "list indices must be integers or slices, not str" };
  }
  if (typeof doc === "string") {
    return { error: "string indices must be integers" };
  }
  if (doc instanceof PyNum) {
    return {
      error:
        "'" + (isIntLiteral(doc.literal) ? "int" : "float") +
        "' object is not subscriptable",
    };
  }
  if (typeof doc === "number") {
    return {
      error:
        "'" + (Number.isInteger(doc) ? "int" : "float") +
        "' object is not subscriptable",
    };
  }
  if (typeof doc === "boolean") {
    return { error: "'bool' object is not subscriptable" };
  }
  return { error: "'NoneType' object is not subscriptable" };
}

/** py tuple(x) over parsed JSON (strings iterate chars, dicts
 *  iterate keys, scalars raise TypeError — verbatim messages). */
function tupleOf(v: unknown): { items: unknown[] } | { error: string } {
  if (Array.isArray(v)) return { items: [...v] };
  if (typeof v === "string") return { items: [...v] };
  if (isPlainObject(v)) return { items: Object.keys(v) };
  if (v instanceof PyTuple) return { items: [...v.items] };
  if (v instanceof PyNum) {
    return {
      error:
        "'" + (isIntLiteral(v.literal) ? "int" : "float") +
        "' object is not iterable",
    };
  }
  if (typeof v === "number") {
    return {
      error:
        "'" + (Number.isInteger(v) ? "int" : "float") +
        "' object is not iterable",
    };
  }
  if (typeof v === "boolean") return { error: "'bool' object is not iterable" };
  return { error: "'NoneType' object is not iterable" };
}

export function tryPromote(
  row: ValidRow,
  outRoot: string,
): PromoteOutcome {
  if (row.origin !== "file" || row.bodyRef === null || row.bodyRef === "") {
    return null;
  }
  const body: string = row.bodyRef;
  const idx: number = body.indexOf("/runs/");
  if (idx < 0) return null;
  const tail: string = body.slice(idx + "/runs/".length);
  if (!tail.includes("/")) return null;
  const runDir: string =
    body.slice(0, idx) + "/runs/" + tail.slice(0, tail.lastIndexOf("/"));
  const paramsRef: string = runDir + "/anny_preset.json";
  let paramsPath: string;
  try {
    paramsPath = resolveArtifactFile(paramsRef, outRoot);
  } catch (exc) {
    // The run delivered no params (regress) — stays file. Any
    // non-refusal error propagates (same as py: only
    // ArtifactRefError is swallowed).
    if (exc instanceof ArtifactRefError) return null;
    throw exc;
  }
  const noParse = (text: string): PromoteOutcome => ({
    refusal:
      "run delivered anny_preset.json but it does not parse as estimated params (" +
      text + ") — fix the run or save mesh-only",
  });
  let doc: unknown;
  try {
    doc = parseJson(readFileSync(paramsPath, "utf-8"));
  } catch (exc) {
    return noParse(osMsg(exc));
  }
  const sph = subscriptKey(doc, "phenotype");
  if ("error" in sph) return noParse(sph.error);
  const ssc = subscriptKey(doc, "scale");
  if ("error" in ssc) return noParse(ssc.error);
  const tph = tupleOf(sph.value);
  if ("error" in tph) return noParse(tph.error);
  const tsc = tupleOf(ssc.value);
  if ("error" in tsc) return noParse(tsc.error);
  // Direct EstimatedParams validation (NO union prefix — locs are
  // bare; the after-validator renders the RAW tuples).
  const errs: VError[] = [];
  const tphV = validFloatTuple(tph.items, ["phenotype"], errs);
  const tscV = validFloatTuple(tsc.items, ["scale"], errs);
  if (tphV === null || tscV === null) {
    return noParse(renderErrors("EstimatedParams", errs));
  }
  if (tphV.nums.length !== 6) {
    return noParse(
      renderErrors("EstimatedParams", [
        vErr(
          [],
          "Value error, estimated phenotype wants 6 dims, got " + tphV.nums.length,
          "value_error",
          {
            phenotype: new PyTuple(tphV.items),
            scale: new PyTuple(tscV.items),
          },
        ),
      ]),
    );
  }
  if (tscV.nums.length !== 139) {
    return noParse(
      renderErrors("EstimatedParams", [
        vErr(
          [],
          "Value error, estimated scale wants 139 entries, got " + tscV.nums.length,
          "value_error",
          {
            phenotype: new PyTuple(tphV.items),
            scale: new PyTuple(tscV.items),
          },
        ),
      ]),
    );
  }
  // The dialect gate runs AFTER construction (a bad-dialect doc
  // with missing dims reports the dims, never the dialect —
  // probed 2026-09-07).
  const dialect: unknown = isPlainObject(doc) ? doc["dialect"] : undefined;
  if (dialect !== "estimated") {
    return {
      refusal:
        "run delivered anny_preset.json with dialect " +
        pyReprValue(dialect) + " (want estimated)",
    };
  }
  return {
    promoted: {
      ...row,
      origin: "estimated",
      params: { kind: "estimated", phenotype: tphV.nums, scale: tscV.nums },
      paramsRef,
    },
  };
}

