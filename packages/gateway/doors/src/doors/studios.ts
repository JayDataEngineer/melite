/** A validated scalar: the JSON number plus its verbatim literal
 *  when the input already was one (ledger round-trips keep
 *  spellings py would keep: ints verbatim, floats via pyFloatRepr
 *  at EMIT time). */
export interface ScalarNum {
  readonly value: number;
  readonly literal: string | null;
}

/** Lax float slot: numbers (finite), bools (True->1.0), numeric
 *  strings ("50"->50.0); failure -> float_parsing at loc. */
function parseFloatLax(
  v: unknown,
  loc: readonly (string | number)[],
  errs: VError[],
): number | null {
  if (v instanceof PyNum) {
    const n: number = Number(v.literal);
    if (!Number.isFinite(n)) {
      errs.push(
        vErr(loc, "Input should be a valid number", "float_type", v),
      );
      return null;
    }
    return n;
  }
  if (typeof v === "number") {
    if (!Number.isFinite(v)) {
      errs.push(vErr(loc, "Input should be a valid number", "float_type", v));
      return null;
    }
    return v;
  }
  if (typeof v === "boolean") return v ? 1 : 0;
  if (typeof v === "string") {
    const t: string = v.trim();
    if (/^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$/.test(t)) {
      const n: number = Number(t);
      if (Number.isFinite(n)) return n;
    }
    errs.push(
      vErr(
        loc,
        "Input should be a valid number, unable to parse string as a number",
        "float_parsing",
        v,
      ),
    );
    return null;
  }
  errs.push(vErr(loc, "Input should be a valid number", "float_type", v));
  return null;
}

/** Lax int slot: ints verbatim, integral floats truncate, bools
 *  (True->1), int-spelled strings ("50"->50); fractional floats ->
 *  int_from_float, bad strings -> int_parsing. */
function parseIntLax(
  v: unknown,
  loc: readonly (string | number)[],
  errs: VError[],
): ScalarNum | null {
  if (v instanceof PyNum) {
    if (isIntLiteral(v.literal)) {
      return { value: Number(v.literal), literal: v.literal };
    }
    const n: number = Number(v.literal);
    if (!Number.isFinite(n)) {
      errs.push(vErr(loc, "Input should be a valid integer", "int_type", v));
      return null;
    }
    if (!Number.isInteger(n)) {
      errs.push(
        vErr(
          loc,
          "Input should be a valid integer, got a number with a fractional part",
          "int_from_float",
          v,
        ),
      );
      return null;
    }
    return { value: n, literal: null };
  }
  if (typeof v === "number") {
    if (!Number.isFinite(v)) {
      errs.push(vErr(loc, "Input should be a valid integer", "int_type", v));
      return null;
    }
    if (!Number.isInteger(v)) {
      errs.push(
        vErr(
          loc,
          "Input should be a valid integer, got a number with a fractional part",
          "int_from_float",
          v,
        ),
      );
      return null;
    }
    return { value: v, literal: null };
  }
  if (typeof v === "boolean") return { value: v ? 1 : 0, literal: null };
  if (typeof v === "string") {
    const t: string = v.trim();
    if (/^[+-]?\d+$/.test(t)) {
      return { value: Number(t), literal: null };
    }
    errs.push(
      vErr(
        loc,
        "Input should be a valid integer, unable to parse string as an integer",
        "int_parsing",
        v,
      ),
    );
    return null;
  }
  errs.push(vErr(loc, "Input should be a valid integer", "int_type", v));
  return null;
}

/** Lax bool slot (probed: "yes"->True): bools, 1/0, and the
 *  pydantic truthy/falsy word set, case-insensitive. */
function parseBoolLax(
  v: unknown,
  loc: readonly (string | number)[],
  errs: VError[],
): boolean | null {
  if (typeof v === "boolean") return v;
  if (v instanceof PyNum && isIntLiteral(v.literal)) {
    if (v.literal === "1" || v.literal === "+1") return true;
    if (v.literal === "0" || v.literal === "-0" || v.literal === "+0") {
      return false;
    }
  }
  if (typeof v === "number" && Number.isInteger(v)) {
    if (v === 1) return true;
    if (v === 0) return false;
  }
  if (typeof v === "string") {
    const t: string = v.trim().toLowerCase();
    if (["true", "1", "yes", "on", "y", "t"].includes(t)) return true;
    if (["false", "0", "no", "off", "n", "f"].includes(t)) return false;
  }
  errs.push(
    vErr(
      loc,
      "Input should be a valid boolean, unable to interpret input",
      "bool_parsing",
      v,
    ),
  );
  return null;
}

/** Strict str slot (min_length/pattern optional). */
function parseStrField(
  v: unknown,
  loc: readonly (string | number)[],
  errs: VError[],
  opts: { minLength?: number; pattern?: RegExp; patternSrc?: string } = {},
): string | null {
  if (typeof v !== "string") {
    errs.push(vErr(loc, "Input should be a valid string", "string_type", v));
    return null;
  }
  if (opts.minLength !== undefined && v.length < opts.minLength) {
    errs.push(
      vErr(
        loc,
        "String should have at least " + opts.minLength + " character" +
          (opts.minLength === 1 ? "" : "s"),
        "string_too_short",
        v,
      ),
    );
    return null;
  }
  if (opts.pattern !== undefined && !opts.pattern.test(v)) {
    errs.push(
      vErr(
        loc,
        "String should match pattern " + pyReprString(opts.patternSrc ?? ""),
        "string_pattern_mismatch",
        v,
      ),
    );
    return null;
  }
  return v;
}

