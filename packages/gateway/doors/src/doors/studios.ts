function isPlainObject(v: unknown): v is Record<string, unknown> {
  if (typeof v !== "object" || v === null || Array.isArray(v)) return false;
  const proto: unknown = Object.getPrototypeOf(v);
  return proto === Object.prototype || proto === null;
}

const PRESET_ID_RE: RegExp = /^[a-z0-9][a-z0-9_\-]*$/;
/** The pattern SOURCE for the mismatch message (py renders the
 *  pattern's repr — the \- doubles to \\ — probed verbatim). */
const PRESET_ID_SRC = "^[a-z0-9][a-z0-9_\\-]*$";

const AUTH_TAG = "function-after[_check_dims(), AuthoredParams]";
const EST_TAG = "function-after[_check_dims(), EstimatedParams]";

/** Required-field fetch (missing -> Field required on the parent). */
function reqField(
  v: Record<string, unknown>,
  key: string,
  loc: readonly (string | number)[],
  errs: VError[],
): { found: boolean; value: unknown } {
  if (!(key in v) || (v as Record<string, unknown>)[key] === undefined) {
    errs.push(vErr([...loc, key], "Field required", "missing", v));
    return { found: false, value: undefined };
  }
  return { found: true, value: (v as Record<string, unknown>)[key] };
}

/** Extra-key sweep (definition-order fields first, extras last in
 *  input order — probed: label/origin miss before zzz extra). */
function extraSweep(
  v: Record<string, unknown>,
  known: ReadonlySet<string>,
  loc: readonly (string | number)[],
  errs: VError[],
): void {
  for (const k of Object.keys(v)) {
    if (!known.has(k)) {
      errs.push(
        vErr(
          [...loc, k],
          "Extra inputs are not permitted",
          "extra_forbidden",
          (v as Record<string, unknown>)[k],
        ),
      );
    }
  }
}

export interface ValidLocalChange {
  readonly name: string;
  readonly value: number;
}

function validLocalChange(
  v: unknown,
  loc: readonly (string | number)[],
  errs: VError[],
): ValidLocalChange | null {
  if (!isPlainObject(v)) {
    errs.push(
      vErr(
        loc,
        "Input should be a valid dictionary or instance of LocalChange",
        "model_type",
        v,
      ),
    );
    return null;
  }
  let bad = false;
  let name = "";
  const rn = reqField(v, "name", loc, errs);
  if (!rn.found) bad = true;
  else {
    const s = parseStrField(rn.value, [...loc, "name"], errs, { minLength: 1 });
    if (s === null) bad = true;
    else name = s;
  }
  let value = 0;
  const rv = reqField(v, "value", loc, errs);
  if (!rv.found) bad = true;
  else {
    const n = parseFloatLax(rv.value, [...loc, "value"], errs);
    if (n === null) bad = true;
    else {
      // Field-level ge/le (fire BEFORE the after-validator — a
      // value of 9 reports less_than_equal, never reaches dup
      // checks; probed 2026-09-07).
      if (n < -1.0) {
        errs.push(
          vErr(
            [...loc, "value"],
            "Input should be greater than or equal to -1",
            "greater_than_equal",
            rv.value,
          ),
        );
        bad = true;
      } else if (n > 2.0) {
        errs.push(
          vErr(
            [...loc, "value"],
            "Input should be less than or equal to 2",
            "less_than_equal",
            rv.value,
          ),
        );
        bad = true;
      } else value = n;
    }
  }
  extraSweep(v, new Set(["name", "value"]), loc, errs);
  return bad ? null : { name, value };
}

/** A validated float tuple's raw items + numbers (promotion
 *  after-errors render the RAW tuple — PyTuple of parsed items). */
interface FloatTuple {
  readonly items: unknown[];
  readonly nums: number[];
}

function validFloatTuple(
  v: unknown,
  loc: readonly (string | number)[],
  errs: VError[],
): FloatTuple | null {
  if (!Array.isArray(v)) {
    errs.push(vErr(loc, "Input should be a valid tuple", "tuple_type", v));
    return null;
  }
  const items: unknown[] = [...v];
  const nums: number[] = [];
  let bad = false;
  for (let i = 0; i < items.length; i++) {
    const n = parseFloatLax(items[i], [...loc, i], errs);
    if (n === null) bad = true;
    else nums.push(n);
  }
  return bad ? null : { items, nums };
}

export interface ValidAuthored {
  readonly phenotype: number[];
  readonly local: ValidLocalChange[];
}

function validAuthored(
  v: unknown,
  locBase: readonly (string | number)[],
  errs: VError[],
): ValidAuthored | null {
  // pydantic runs the model_after validator only when the fields
  // validate — ANY error so far (fields OR extras) skips it.
  const errsBefore: number = errs.length;
  if (!isPlainObject(v)) {
    errs.push(
      vErr(
        locBase,
        "Input should be a valid dictionary or instance of AuthoredParams",
        "model_type",
        v,
      ),
    );
    return null;
  }
  let bad = false;
  let ph: number[] | null = null;
  const rp = reqField(v, "phenotype", locBase, errs);
  if (!rp.found) bad = true;
  else {
    const t = validFloatTuple(rp.value, [...locBase, "phenotype"], errs);
    if (t === null) bad = true;
    else ph = t.nums;
  }
  let local: ValidLocalChange[] = [];
  if ("local_changes" in v && v["local_changes"] !== undefined) {
    const lv = v["local_changes"];
    if (!Array.isArray(lv)) {
      errs.push(
        vErr([...locBase, "local_changes"], "Input should be a valid tuple", "tuple_type", lv),
      );
      bad = true;
    } else {
      const acc: ValidLocalChange[] = [];
      for (let i = 0; i < lv.length; i++) {
        const lc = validLocalChange(lv[i], [...locBase, "local_changes", i], errs);
        if (lc === null) bad = true;
        else acc.push(lc);
      }
      local = acc;
    }
  }
  extraSweep(v, new Set(["phenotype", "local_changes"]), locBase, errs);
  if (errs.length !== errsBefore || ph === null) return null;
  // _check_dims (after — runs only when the fields pass, exactly
  // like pydantic's after-validator; input_value is the branch
  // dict, truncation applies).
  if (ph.length !== 11) {
    errs.push(
      vErr(locBase, "Value error, authored phenotype wants 11 dims, got " + ph.length, "value_error", v),
    );
    return null;
  }
  for (let i = 0; i < ph.length; i++) {
    const n: number = ph[i] as number;
    if (!(n >= 0.0 && n <= 1.0)) {
      errs.push(
        vErr(
          locBase,
          "Value error, authored phenotype[" + i + "] = " +
            pyFloatRepr(n) + " outside 0.0..1.0",
          "value_error",
          v,
        ),
      );
      return null;
    }
  }
  const seen = new Set<string>();
  for (const lc of local) {
    if (seen.has(lc.name)) {
      errs.push(
        vErr(
          locBase,
          "Value error, duplicate local-change morph " + pyReprString(lc.name),
          "value_error",
          v,
        ),
      );
      return null;
    }
    seen.add(lc.name);
  }
  return { phenotype: ph, local };
}

export interface ValidEstimated {
  readonly phenotype: number[];
  readonly scale: number[];
}

function validEstimated(
  v: unknown,
  locBase: readonly (string | number)[],
  errs: VError[],
): ValidEstimated | null {
  // (same after-skip law as the authored branch)
  const errsBefore: number = errs.length;
  if (!isPlainObject(v)) {
    errs.push(
      vErr(
        locBase,
        "Input should be a valid dictionary or instance of EstimatedParams",
        "model_type",
        v,
      ),
    );
    return null;
  }
  let bad = false;
  let ph: number[] | null = null;
  const rp = reqField(v, "phenotype", locBase, errs);
  if (!rp.found) bad = true;
  else {
    const t = validFloatTuple(rp.value, [...locBase, "phenotype"], errs);
    if (t === null) bad = true;
    else ph = t.nums;
  }
  let sc: number[] | null = null;
  const rs = reqField(v, "scale", locBase, errs);
  if (!rs.found) bad = true;
  else {
    const t = validFloatTuple(rs.value, [...locBase, "scale"], errs);
    if (t === null) bad = true;
    else sc = t.nums;
  }
  extraSweep(v, new Set(["phenotype", "scale"]), locBase, errs);
  if (errs.length !== errsBefore || ph === null || sc === null) {
    return null;
  }
  if (ph.length !== 6) {
    errs.push(
      vErr(locBase, "Value error, estimated phenotype wants 6 dims, got " + ph.length, "value_error", v),
    );
    return null;
  }
  if (sc.length !== 139) {
    errs.push(
      vErr(locBase, "Value error, estimated scale wants 139 entries, got " + sc.length, "value_error", v),
    );
    return null;
  }
  return { phenotype: ph, scale: sc };
}

export type ValidParams =
  | { readonly kind: "authored"; readonly phenotype: number[]; readonly local: ValidLocalChange[] }
  | { readonly kind: "estimated"; readonly phenotype: number[]; readonly scale: number[] };

/** The params union (Authored first, then Estimated — definition
 *  order; BOTH error lists concatenate on failure, probed). */
function validParamsUnion(v: unknown, errs: VError[]): ValidParams | null {
  const aErrs: VError[] = [];
  const a = validAuthored(v, ["params", AUTH_TAG], aErrs);
  if (aErrs.length === 0 && a !== null) {
    return { kind: "authored", phenotype: a.phenotype, local: a.local };
  }
  const bErrs: VError[] = [];
  const b = validEstimated(v, ["params", EST_TAG], bErrs);
  if (bErrs.length === 0 && b !== null) {
    return { kind: "estimated", phenotype: b.phenotype, scale: b.scale };
  }
  errs.push(...aErrs, ...bErrs);
  return null;
}

export interface ValidParts {
  readonly hair: string | null;
  readonly outfit: string | null;
}

function validParts(
  v: unknown,
  locBase: readonly (string | number)[],
  errs: VError[],
): ValidParts | null {
  if (v === undefined) return { hair: null, outfit: null };
  if (!isPlainObject(v)) {
    errs.push(
      vErr(
        locBase,
        "Input should be a valid dictionary or instance of PresetParts",
        "model_type",
        v,
      ),
    );
    return null;
  }
  let bad = false;
  const hair = optStr(v, "hair", locBase, errs);
  const outfit = optStr(v, "outfit", locBase, errs);
  if (hair === undefined || outfit === undefined) bad = true;
  extraSweep(v, new Set(["hair", "outfit"]), locBase, errs);
  return bad ? null : { hair: hair ?? null, outfit: outfit ?? null };
}

/** Optional str slot (missing/undefined/null -> None). */
function optStr(
  v: Record<string, unknown>,
  key: string,
  loc: readonly (string | number)[],
  errs: VError[],
): string | null | undefined {
  if (!(key in v) || v[key] === undefined || v[key] === null) return null;
  const s = parseStrField(v[key], [...loc, key], errs);
  return s === null ? undefined : s;
}

export interface ValidKnobs {
  readonly resolution: ScalarNum | null;
  readonly framing: string | null;
  readonly focalLength: number | null;
  readonly samples: ScalarNum | null;
  readonly transparent: boolean | null;
}

function validKnobs(
  v: unknown,
  locBase: readonly (string | number)[],
  errs: VError[],
): ValidKnobs | null {
  if (v === undefined) {
    return { resolution: null, framing: null, focalLength: null, samples: null, transparent: null };
  }
  if (!isPlainObject(v)) {
    errs.push(
      vErr(
        locBase,
        "Input should be a valid dictionary or instance of PresetKnobs",
        "model_type",
        v,
      ),
    );
    return null;
  }
  let bad = false;
  const get = (key: string): unknown =>
    key in v && v[key] !== undefined ? v[key] : null;
  let resolution: ScalarNum | null = null;
  const rv = get("resolution");
  if (rv !== null) {
    const n = parseIntLax(rv, [...locBase, "resolution"], errs);
    if (n === null) bad = true;
    else resolution = n;
  }
  let framing: string | null = null;
  const fv = get("framing");
  if (fv !== null) {
    const s = parseStrField(fv, [...locBase, "framing"], errs);
    if (s === null) bad = true;
    else framing = s;
  }
  let focalLength: number | null = null;
  const lv = get("focal_length");
  if (lv !== null) {
    const n = parseFloatLax(lv, [...locBase, "focal_length"], errs);
    if (n === null) bad = true;
    else focalLength = n;
  }
  let samples: ScalarNum | null = null;
  const sv = get("samples");
  if (sv !== null) {
    const n = parseIntLax(sv, [...locBase, "samples"], errs);
    if (n === null) bad = true;
    else samples = n;
  }
  let transparent: boolean | null = null;
  const tv = get("transparent");
  if (tv !== null) {
    const b = parseBoolLax(tv, [...locBase, "transparent"], errs);
    if (b === null) bad = true;
    else transparent = b;
  }
  extraSweep(
    v,
    new Set(["resolution", "framing", "focal_length", "samples", "transparent"]),
    locBase,
    errs,
  );
  return bad
    ? null
    : { resolution, framing, focalLength, samples, transparent };
}

const ORIGINS = ["base_params", "estimated", "file"] as const;
export type Origin = (typeof ORIGINS)[number];

export interface ValidRow {
  id: string;
  label: string;
  description: string;
  origin: Origin;
  params: ValidParams | null;
  paramsRef: string | null;
  bodyRef: string | null;
  parts: ValidParts;
  knobs: ValidKnobs;
}

/** CharacterPreset construction (field order id/label/description/
 *  origin/params/params_ref/body_ref/parts/knobs — definition
 *  order; the after-validator runs ONLY when the fields pass,
 *  probed: a bad label suppresses the coherence error). The input
 *  is the {id: sentinel, ...body} dict for saves, the ledger row
 *  dict for reads — key order feeds truncated reprs, so callers
 *  must preserve it. */
export function validCharacterPreset(
  input: unknown,
  errs: VError[],
): ValidRow | null {
  if (!isPlainObject(input)) {
    errs.push(
      vErr(
        [],
        "Input should be a valid dictionary or instance of CharacterPreset",
        "model_type",
        input,
      ),
    );
    return null;
  }
  let bad = false;
  let id = "";
  const ri = reqField(input, "id", [], errs);
  if (!ri.found) bad = true;
  else {
    const s = parseStrField(ri.value, ["id"], errs, {
      pattern: PRESET_ID_RE,
      patternSrc: PRESET_ID_SRC,
    });
    if (s === null) bad = true;
    else id = s;
  }
  let label = "";
  const rl = reqField(input, "label", [], errs);
  if (!rl.found) bad = true;
  else {
    const s = parseStrField(rl.value, ["label"], errs, { minLength: 1 });
    if (s === null) bad = true;
    else label = s;
  }
  let description = "";
  if ("description" in input && input["description"] !== undefined) {
    const s = parseStrField(input["description"], ["description"], errs);
    if (s === null) bad = true;
    else description = s;
  }
  let origin: Origin = "file";
  const ro = reqField(input, "origin", [], errs);
  if (!ro.found) bad = true;
  else if (
    ro.value !== "base_params" &&
    ro.value !== "estimated" &&
    ro.value !== "file"
  ) {
    errs.push(
      vErr(
        ["origin"],
        "Input should be 'base_params', 'estimated' or 'file'",
        "enum",
        ro.value,
      ),
    );
    bad = true;
  } else origin = ro.value;
  let params: ValidParams | null = null;
  if ("params" in input && input["params"] !== undefined && input["params"] !== null) {
    const p = validParamsUnion(input["params"], errs);
    if (p === null) bad = true;
    else params = p;
  }
  let paramsRef: string | null = null;
  if ("params_ref" in input && input["params_ref"] !== undefined && input["params_ref"] !== null) {
    const s = parseStrField(input["params_ref"], ["params_ref"], errs);
    if (s === null) bad = true;
    else paramsRef = s;
  }
  let bodyRef: string | null = null;
  if ("body_ref" in input && input["body_ref"] !== undefined && input["body_ref"] !== null) {
    const s = parseStrField(input["body_ref"], ["body_ref"], errs);
    if (s === null) bad = true;
    else bodyRef = s;
  }
  let parts: ValidParts = { hair: null, outfit: null };
  if ("parts" in input && input["parts"] !== undefined) {
    const p = validParts(input["parts"], ["parts"], errs);
    if (p === null) bad = true;
    else parts = p;
  }
  let knobs: ValidKnobs = {
    resolution: null,
    framing: null,
    focalLength: null,
    samples: null,
    transparent: null,
  };
  if ("knobs" in input && input["knobs"] !== undefined) {
    const k = validKnobs(input["knobs"], ["knobs"], errs);
    if (k === null) bad = true;
    else knobs = k;
  }
  extraSweep(
    input,
    new Set([
      "id",
      "label",
      "description",
      "origin",
      "params",
      "params_ref",
      "body_ref",
      "parts",
      "knobs",
    ]),
    [],
    errs,
  );
  // Nested extras (parts/knobs/local_changes) push without setting
  // bad — the top model still refuses whenever anything failed.
  if (bad || errs.length > 0) return null;
  // _check_origin_coherence (order + texts verbatim from
  // infra/python/melite_models/presets.py — the dialect-mismatch errors fire
  // AFTER the presence errors, and params_ref-before-dialect
  // within each branch).
  if (origin === "file") {
    if (params !== null || paramsRef !== null) {
      errs.push(
        vErr(
          [],
          "Value error, file-origin preset carries no params — mesh only (params/params_ref must be None)",
          "value_error",
          input,
        ),
      );
      return null;
    }
  } else {
    if (params === null) {
      errs.push(
        vErr(
          [],
          "Value error, " + origin + " preset without params — coefficients are the character",
          "value_error",
          input,
        ),
      );
      return null;
    }
    if (origin === "estimated") {
      if (paramsRef === null) {
        errs.push(
          vErr(
            [],
            "Value error, estimated preset without params_ref — the source run artifact is the provenance",
            "value_error",
            input,
          ),
        );
        return null;
      }
      if (params.kind !== "estimated") {
        errs.push(
          vErr(
            [],
            "Value error, estimated preset must speak the estimated dialect (verbatim estimator output)",
            "value_error",
            input,
          ),
        );
        return null;
      }
    } else {
      if (paramsRef !== null) {
        errs.push(
          vErr(
            [],
            "Value error, base_params preset with params_ref — authored coefficients ARE the source",
            "value_error",
            input,
          ),
        );
        return null;
      }
      if (params.kind !== "authored") {
        errs.push(
          vErr(
            [],
            "Value error, base_params preset must speak the authored dialect (11-dim + named morphs)",
            "value_error",
            input,
          ),
        );
        return null;
      }
    }
  }
  return { id, label, description, origin, params, paramsRef, bodyRef, parts, knobs };
}

