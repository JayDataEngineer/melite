function emitInt(n: ScalarNum): unknown {
  return n.literal !== null ? new PyNum(n.literal) : n.value;
}

function emitFloat(n: number): unknown {
  return new PyNum(pyFloatRepr(n));
}

/** model_dump(mode="json") — definition-order dict (floats via
 *  pyFloatRepr so 1 wires "1.0" and True wires 1.0; ints ride
 *  verbatim when the input spelled them). */
export function dumpRow(row: ValidRow): Record<string, unknown> {
  return {
    id: row.id,
    label: row.label,
    description: row.description,
    origin: row.origin,
    params:
      row.params === null
        ? null
        : row.params.kind === "authored"
          ? {
              phenotype: row.params.phenotype.map(emitFloat),
              local_changes: row.params.local.map((lc) => ({
                name: lc.name,
                value: emitFloat(lc.value),
              })),
            }
          : {
              phenotype: row.params.phenotype.map(emitFloat),
              scale: row.params.scale.map(emitFloat),
            },
    params_ref: row.paramsRef,
    body_ref: row.bodyRef,
    parts: { hair: row.parts.hair, outfit: row.parts.outfit },
    knobs: {
      resolution: row.knobs.resolution === null ? null : emitInt(row.knobs.resolution),
      framing: row.knobs.framing,
      focal_length: row.knobs.focalLength === null ? null : emitFloat(row.knobs.focalLength),
      samples: row.knobs.samples === null ? null : emitInt(row.knobs.samples),
      transparent: row.knobs.transparent,
    },
  };
}

/** canonical_json (sorted keys, compact — the bake dialect the
 *  studio posts verbatim; local_changes as the node's OBJECT). */
export function canonicalJson(row: ValidRow): string {
  if (row.params === null) throw new Error("no params");
  if (row.params.kind === "authored") {
    const lc: string =
      "{" +
      row.params.local
        .map((e) => dumpsPy(e.name) + ":" + pyFloatRepr(e.value))
        .join(",") +
      "}";
    return (
      '{"dialect":"authored","local_changes":' +
      lc +
      ',"phenotype":[' +
      row.params.phenotype.map(pyFloatRepr).join(",") +
      "]}"
    );
  }
  return (
    '{"dialect":"estimated","phenotype":[' +
    row.params.phenotype.map(pyFloatRepr).join(",") +
    '],"scale":[' +
    row.params.scale.map(pyFloatRepr).join(",") +
    "]}"
  );
}

