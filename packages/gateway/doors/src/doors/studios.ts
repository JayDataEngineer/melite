  if (engine === "") return null;
  const ep: Record<string, unknown> = readEndpoint(repoRoot, engine);
  const folders: unknown = ep["extra_model_folders"];
  const fmap: Record<string, unknown> =
    isPlainObject(folders) ? folders : {};
