export function probe(url: string, path: string,
    timeoutMs = 5000): { status: number; text: string } {
  const u = new URL(url.replace(/\/$/, "") + path);
  // Synchronous probe via a one-shot child fetch (no estate code —
  // flag + URL only; node has no sync HTTP client).
  const r = spawnSync(process.execPath, ["-e",
    "fetch(process.argv[1]).then(async r=>{const t=await r.text();" +
    "process.stdout.write(r.status+'\\n'+t)})" +
    ".catch(e=>{console.error(String(e).slice(0,200));process.exit(1)})",
    u.toString()],
    { encoding: "utf8", timeout: timeoutMs + 2000, maxBuffer: 64 << 20 });
  if (r.status !== 0) {
    throw new Error((r.stderr || "fetch failed").trim().slice(0, 120));
  }
  const nl = (r.stdout ?? "").indexOf("\n");
  return { status: parseInt((r.stdout ?? "").slice(0, nl), 10),
    text: (r.stdout ?? "").slice(nl + 1) };
}

/** The generated yaml's exact body — ONE owner shared by the writer
 *  (cmdPaths) and the wiring-roots wall, which recomputes it from
 *  the config and refuses a stale file (the wiring-roots audit,
 *  2026-10-13: nothing reconciled the generated roots with the
 *  config that should have produced them).
 *  @param bound the bound layout (base, download, folder map).
 *  @returns the full file body, trailing newline included. */
export function wiringYamlBody(bound: BoundLayout): string {
  const base = bound.base_path;
  const folders = bound.folders;
  const lines = [
    "# generated by provision paths — DO NOT hand-edit",
    "# (source of truth: inference.config.json at the repo root — " +
    "endpoint storage keys override when set)",
    "melite_weights:",
    "  base_path: " + base,
  ];
  for (const f of FIXED_FOLDERS) lines.push("  " + f + ": " + folders[f]);
  const extras = Object.keys(folders).filter((f) => !FIXED_FOLDERS.includes(f));
  if (extras.length > 0) {
    lines.push("  # pack-declared categories (extra_model_folders)");
    for (const f of extras) lines.push("  " + f + ": " + folders[f]);
  }
  // ComfyUI-Manager writes model downloads under
  // folder_paths["download_model_base"][0][0] when that folder name
  // is registered (manager glob/manager_server.py get_model_dir), and
  // under its own models/ otherwise. The loader in core
  // comfy/utils/extra_config.py registers one folder name per
  // remaining key, so the `download_model_base: .` key registers the
  // store itself — every Manager model install then lands inside the
  // estate store the endpoint config binds (desktop receipt:
  // sam_vit_b_01ec64 landed at the store's sams/ on the first queue
  // attempt).
  lines.push(
    "download_model_base:",
    "  base_path: " + bound.download_path,
    "  download_model_base: .",
  );
  return lines.join("\n") + "\n";
}

/**
 * Creates the model store the dead-root refusal names (fresh-clone
 * gate, 2026-10-17): `paths`/`sync` refuse a store that does not
 * exist — loud by law, catching typoed roots — but a fresh clone
 * has no store at all, and "create the store" was a hand-carried
 * mkdir with no door. This verb IS the named action: it lays the
 * two bound roots plus every category directory under the download
 * root, idempotently. It never runs inside `paths` (that would
 * create a typoed root silently — the exact bug the refusal
 * cures); a plain FILE in place of either root still refuses.
 *
 * @param cfg the endpoint config (storage overrides resolve like `paths`)
 */
export function cmdInitStore(cfg: EndpointConfig): void {
  const bound = boundModelFolders(cfg);
  for (const [k, root] of [["base_path", bound.base_path],
    ["download_path", bound.download_path]] as const) {
    const st = lstatSync(root, { throwIfNoEntry: false });
    if (st !== undefined && st.isFile()) {
      throw new Error(
        `[init-store] the resolved ${k} is a file, not a directory: ` +
        root + " — move it or fix models.read_root in " +
        "inference.config.json (never guessed)");
    }
  }
  const created: string[] = [bound.base_path, bound.download_path];
  for (const cat of Object.keys(bound.folders).sort()) {
    created.push(join(bound.download_path, bound.folders[cat]));
  }
  for (const dir of created) mkdirSync(dir, { recursive: true });
  console.log("init-store: " + created.length + " directories laid at " +
    bound.base_path + " (existing ones untouched)");
}

export function cmdPaths(cfg: EndpointConfig): void {
  const bound = boundModelFolders(cfg);
  // THE DEAD-ROOT REFUSAL (wiring re-audit F7, 2026-10-13): the
  // empty-string guard in boundModelFolders refuses an UNSET root,
  // but a TYPOED one sailed through — the yaml mounted a path that
  // does not exist, ComfyUI silently served empty enums for every
  // category under it, and lanes refused at /prompt with the
  // weights "present" on disk. The refusal lives at provision
  // time (here), never in the pure derivation: the wiring-roots
  // wall recomputes boundModelFolders on CI seats where the store
  // is legitimately absent.
  for (const [k, root] of [["base_path", bound.base_path],
    ["download_path", bound.download_path]] as const) {
    if (!existsSync(root)) {
      throw new Error(
        `[paths] the resolved ${k} does not exist on this machine: ${root} — ` +
        "a dead root is not mounted (ComfyUI serves empty enums for it, " +
        "silently); create the store or fix models.read_root in " +
        "inference.config.json (never guessed)",
      );
    }
  }
  mkdirSync(join(runtime(), "custom_nodes"), { recursive: true });
  mkdirSync(join(runtime(), "user"), { recursive: true });
  writeFileSync(join(runtime(), "extra_model_paths.yaml"), wiringYamlBody(bound));
  console.log("runtime layout + extra_model_paths.yaml → " + runtime());
  layDownloadPointers(bound.download_path, bound.folders);
  syncEndpointFromRoot(cfg);
}

export function layDownloadPointers(downloadBase: string,
    folders: Record<string, string>,
    modelsDir: string = join(runtime(), "models")): void {
  // Every category dir inside the runtime is a symlink onto the
  // CONFIGURED destination, so every writer (comfy-cli, pack
  // auto-download, core) lands exactly where the endpoint config
  // says. Self-healing: real content moves first, then the pointer
  // is laid.
  mkdirSync(modelsDir, { recursive: true });
  for (const cat of Object.keys(folders).sort()) {
    const local = join(modelsDir, cat);
    const target = join(downloadBase, folders[cat]);
    try {
      if (realpathSync(local) === target) continue;
    } catch { /* not a correct pointer */ }
    // lstat, not stat: stat follows the pointer, so a DANGLING link
    // (target moved or deleted) reads as absent and the relink below
    // dies EEXIST — the second `paths` run was fatal (ledger
    // li-paths-idempotence). lstat sees the link itself: dangling or
    // healthy, it is unlinked and re-laid; a stray plain file blocks
    // the pointer the same way and is removed too.
    const st = lstatSync(local, { throwIfNoEntry: false });
    if (st?.isSymbolicLink() || st?.isFile()) unlinkSync(local);
    else if (st?.isDirectory()) {
      mkdirSync(target, { recursive: true });
      for (const f of readdirSync(local)) {
        const dest = join(target, f);
        if (existsSync(dest)) continue;
        // rename first (same-device: atomic, free); EXDEV (the repo
        // tree and the store on different mounts) falls back to
        // copy+unlink — the wiring-roots cure exposed this when five
        // new categories moved their first weights across devices
        // and the self-heal leg died fatal mid-move.
        try {
          renameSync(join(local, f), dest);
        } catch (e) {
          if ((e as NodeJS.ErrnoException).code !== "EXDEV") throw e;
          copyFileSync(join(local, f), dest);
          unlinkSync(join(local, f));
        }
      }
      rmSync(local, { recursive: true });
    }
    mkdirSync(target, { recursive: true });
    if (!existsSync(local)) symlinkSync(target, local);
  }
  console.log("download pointers: " + Object.keys(folders).length +
    " categories → " + downloadBase + " (configured model_download_path)");
}

/**
 * Removes every symlink directly under the runtime's models dir —
 * the pointer layer `layDownloadPointers` owns. THE BUMP COLLISION
 * (audit 005/E5, 2026-10-22): a pin hop onto a provisioned tree
 * meets the pointers as symlinks over tracked placeholder dirs;
 * `git checkout` of a target that changes those placeholders aborts
 * on the local deletion, and one that recreates their parent dirs
 * writes THROUGH the link into the model store. Detaching the
 * pointers first gives the checkout a clean tracked surface; the
 * layout re-lays them right after (checkout precedes `paths` — the
 * ORDER LAW, now on every hop, not only the first provision).
 * Content never moves: pointers are links, the store keeps
 * everything.
 *
 * @param modelsDir the runtime's models dir (default: the
 *        provisioned runtime's own)
 * @returns the detached pointer names (empty when none were laid)
 */
export function detachModelPointers(
    modelsDir: string = join(runtime(), "models")): string[] {
  const detached: string[] = [];
  if (!existsSync(modelsDir)) return detached;
  for (const e of readdirSync(modelsDir, { withFileTypes: true })) {
    const p = join(modelsDir, e.name);
    if (lstatSync(p, { throwIfNoEntry: false })?.isSymbolicLink()) {
      unlinkSync(p);
      detached.push(e.name);
    }
  }
  return detached;
}

export const ENDPOINT_DERIVED: readonly string[] = ["url", "model_base_path",
  "model_download_path", "input_dir", "input_dir_container", "output_dir",
  "boot_cmd"];

/**
 * The writable form of a derived path for the TRACKED endpoint file:
 * repo-relative stays relative, an absolute path under the repository
 * is stored relative to the repo root, and a machine absolute outside
 * the repository returns null — that value belongs to the untracked
 * machine overlay (data/inference.local.json), never to a file a
 * fresh clone shares (ledger li-portability).
 *
 * @param value the derived machine-resolved path
 * @returns the tracked-file-safe form, or null when the overlay owns it
 */
export function endpointWritable(value: string,
    root: string = repo()): string | null {
  const v = value.trim();
  if (v === "") return v;
  if (!isAbsolute(v)) return v;
  const rel = relative(root, v);
  if (rel !== "" && !rel.startsWith("..") && !isAbsolute(rel)) {
    return rel.split(sep).join("/");
  }
  return null;
}

export function syncEndpointFromRoot(cfg: EndpointConfig): void {
  // The endpoint's url, model_*, stream and boot_cmd keys are derived
  // from the root config (the endpoint file is a generated surface
  // for these fields). An explicit endpoint value still wins when
  // SET; unset inherits the root. boot_cmd's --port is rewritten
  // from the resolved port (the port-drift gap). Path values are
  // written only in their tracked-file-safe form — a machine
  // absolute outside the repo stays in the untracked overlay and is
  // deliberately NOT written here.
  const root = loadRoot();
  const url = engineField(root, "url", cfg.url);
  const port = enginePort(cfg);
  const bootRaw = engineField(root, "boot_cmd", cfg.boot_cmd);
  const boot = bootRaw.replace(/--port \d+/, "--port " + port);
  const paths = boundModelFolders(cfg);
  const derived: Record<string, string> = {
    model_base_path: paths.base_path,
    model_download_path: paths.download_path,
    url,
    input_dir: anchorDir(engineField(root, "input_dir", cfg.input_dir)),
    input_dir_container: engineField(root, "input_dir_container",
      cfg.input_dir_container),
    output_dir: anchorDir(engineField(root, "output_dir", cfg.output_dir)),
    boot_cmd: boot,
  };
  const changed: string[] = [];
  const skipped: string[] = [];
  const next: Record<string, string> = {};
  for (const [k, v] of Object.entries(derived)) {
    // Path keys record themselves only as EXPLICIT endpoint overrides
    // of the root config — an unset key inherits the root and stays
    // unset in the tracked file (li-portability: the tracked shape
    // carries no redundant derivations; url/boot_cmd/containers are
    // generated-surface facts and always record).
    const override = k === "model_base_path" || k === "model_download_path" ||
      k === "input_dir" || k === "output_dir"
      ? rootStr(String((cfg as Record<string, unknown>)[k] ?? "")) !== ""
      : true;
    const writable = k === "input_dir_container" ? v : endpointWritable(v);
    if (writable === null || !override) {
      skipped.push(k);
      continue;
    }
    next[k] = writable;
    if (String((cfg as Record<string, unknown>)[k] ?? "").trim() !==
        writable.trim()) {
      changed.push(k);
      (cfg as Record<string, unknown>)[k] = writable;
    }
  }
  if (changed.length === 0) return;
  const onDisk = JSON.parse(readFileSync(defaultConfig(), "utf8")) as
    Record<string, unknown>;
  for (const k of ENDPOINT_DERIVED) {
    if (k in next) onDisk[k] = next[k];
  }
  writeFileSync(defaultConfig(), JSON.stringify(onDisk, null, 2) + "\n");
  console.log("endpoint derived from root: " + changed.join(", ") +
    (skipped.length > 0
      ? " (not written — inherited or overlay-owned: " + skipped.join(", ") + ")"
      : ""));
}

// ── BYO attach: the extra_model_paths door (audit 019 C4) ───────
//
// A BYO engine reads model folders through exactly ONE mechanism:
// `<engineRoot>/extra_model_paths.yaml`, loaded unconditionally at
// boot (main.py apply_custom_paths), plus any files named explicitly
// on --extra-model-paths-config. There is NO drop-in directory: the
// upstream loader (utils/extra_config.py load_extra_path_config)
// takes single file paths only — verified against the live engine
// checkout (87ed5a06, 2026-10-20). So the honest door for a LOCAL BYO
// engine is a MARKED BLOCK appended to that single file: melite owns
// its block bytes and nothing else of the user's file, the write is
// idempotent, and a probe asks the RUNNING engine whether the store's
// folders are visible (read-only GET /models/<folder> — never a POST,
// never a restart).

/** Begin marker of melite's owned block in a BYO engine's
 *  extra_model_paths.yaml. Everything between this and
 *  {@link BYO_BLOCK_END} is melite's; every byte outside is the
 *  user's, never read for meaning and never rewritten. */
export const BYO_BLOCK_BEGIN: string =
  "# >>> melite byo-attach (generated — delete this whole block to detach) >>>";

/** End marker of melite's owned block. */
export const BYO_BLOCK_END: string = "# <<< melite byo-attach <<<";

/**
 * The engine-root file the door writes: the single extra-path config
 * ComfyUI reads automatically at boot.
 * @param engineRoot the ComfyUI checkout dir (the dir holding main.py)
 * @returns absolute path of <engineRoot>/extra_model_paths.yaml
 */
export function byoExtraPathsFile(engineRoot: string): string {
  return join(engineRoot, "extra_model_paths.yaml");
}

/**
 * The folder map the block binds: stock categories map to themselves,
 * pack-declared categories ride the endpoint statement's
 * extra_model_folders (the same mapping the managed wiring binds —
 * one store schema, two attach planes).
 * @param extras the endpoint statement's extra_model_folders (optional)
 * @returns {folder: store subdir} with stock folders first
 */
export function byoFolderMap(
    extras?: Record<string, string>): Record<string, string> {
  const folders: Record<string, string> = {};
  for (const f of FIXED_FOLDERS) folders[f] = f;
  for (const cat of Object.keys(extras ?? {}).sort()) {
    const sub = String(extras?.[cat] ?? "").trim().replace(/^\/+|\/+$/g, "");
    if (cat.trim() && sub) folders[cat.trim()] = sub;
  }
  return folders;
}

/**
 * Melite's marked block body — the yaml ComfyUI's loader consumes:
 * a top-level `melite_weights` key (base_path + every folder) plus
 * the `download_model_base` registration so Manager downloads land
 * in the store (same key semantics as the managed wiringYamlBody).
 * The base_path is written ABSOLUTE: a relative one would resolve
 * against the yaml's own dir, and the store is the estate's own
 * statement, not the engine tree's tenant.
 * @param storeRoot the model store root the estate acquires into
 * @param extras the endpoint statement's extra_model_folders (optional)
 * @returns the full block body, markers included, trailing newline
 */
export function byoExtraPathsBlock(storeRoot: string,
    extras?: Record<string, string>): string {
  const folders = byoFolderMap(extras);
  const lines: string[] = [
    BYO_BLOCK_BEGIN,
    "# melite's model store, attached to THIS engine. Regenerate with",
    "# the provisioner; deleting the whole block detaches the store.",
    "melite_weights:",
    "  base_path: " + storeRoot,
  ];
  for (const f of FIXED_FOLDERS) lines.push("  " + f + ": " + folders[f]);
  const extraKeys = Object.keys(folders)
    .filter((f) => !FIXED_FOLDERS.includes(f));
  if (extraKeys.length > 0) {
    lines.push("  # pack-declared categories (extra_model_folders)");
    for (const f of extraKeys) lines.push("  " + f + ": " + folders[f]);
  }
  lines.push(
    "download_model_base:",
    "  base_path: " + storeRoot,
    "  download_model_base: .",
    BYO_BLOCK_END,
  );
  return lines.join("\n") + "\n";
}

/** Result of {@link writeByoExtraPaths}. */
export interface ByoWriteResult {
  /** The file the block lives in. */
  path: string;
  /** Whether bytes changed this call (false = already exact). */
  wrote: boolean;
  /** Whether the file did not exist before this call. */
  created: boolean;
}

/**
 * Link melite's model store into a LOCAL BYO engine's extra-path
 * mechanism: create the engine's extra_model_paths.yaml, or append
 * melite's marked block after the user's content, or replace the
 * existing marked block in place. IDEMPOTENT: a call whose block is
 * already byte-exact writes nothing. LOUD refusals (never silently
 * skip): an engine root that is not a ComfyUI tree, a torn block
 * (begin marker without its end), a store root that does not exist
 * (ComfyUI serves empty enums for dead roots — the wiring re-audit
 * F7 law).
 *
 * @param engineRoot the ComfyUI checkout dir (the dir holding main.py)
 * @param storeRoot the model store root the estate acquires into
 * @param extras the endpoint statement's extra_model_folders (optional)
 * @returns what was written (wrote=false when already exact)
 */
export function writeByoExtraPaths(engineRoot: string, storeRoot: string,
    extras?: Record<string, string>): ByoWriteResult {
  const rootSt = lstatSync(engineRoot, { throwIfNoEntry: false });
  if (rootSt === undefined || rootSt.isFile()) {
    throw new Error(
      "[byo-attach] engine root does not exist: " + engineRoot +
      " — name the ComfyUI checkout dir (the dir holding main.py); " +
      "never guessed");
  }
  if (!existsSync(join(engineRoot, "main.py")) &&
      !existsSync(join(engineRoot, "folder_paths.py"))) {
    throw new Error(
      "[byo-attach] " + engineRoot + " is not a ComfyUI tree (no " +
      "main.py / folder_paths.py) — name the engine's own checkout " +
      "dir, never guessed");
  }
  if (!existsSync(storeRoot)) {
    throw new Error(
      "[byo-attach] the model store does not exist: " + storeRoot +
      " — create the store (provision init-store) or fix " +
      "models.read_root in inference.config.json (never guessed)");
  }
  const file = byoExtraPathsFile(engineRoot);
  const block = byoExtraPathsBlock(storeRoot, extras);
  const existing: string | null =
    existsSync(file) ? readFileSync(file, "utf8") : null;
  if (existing === null) {
    writeFileSync(file, block);
    return { path: file, wrote: true, created: true };
  }
  const begin = existing.indexOf(BYO_BLOCK_BEGIN);
  if (begin < 0) {
    // Fresh append: the user's bytes stay byte-identical up front.
    const sep = existing.endsWith("\n") ? "\n" : "\n\n";
    writeFileSync(file, existing + sep + block);
    return { path: file, wrote: true, created: false };
  }
  const end = existing.indexOf(BYO_BLOCK_END, begin);
  if (end < 0) {
    throw new Error(
      "[byo-attach] torn byo-attach block in " + file + " (begin " +
      "marker without its end) — fix or delete the block by hand; " +
      "the writer never guesses where it ends");
  }
  const after = existing.slice(end + BYO_BLOCK_END.length)
    .replace(/^\r?\n/, "");
  const next = existing.slice(0, begin) + block + after;
  if (next === existing) return { path: file, wrote: false, created: false };
  writeFileSync(file, next);
  return { path: file, wrote: true, created: false };
}

/**
 * Derive the BYO attach pair from the machine's own statements: the
 * engine root from the explicit argument, else the endpoint
 * statement's `engine_root`, else the machine overlay's
 * engines.comfyui.live_root; the store from the bound layout's
 * download root (the store the estate acquires into — the same base
 * the managed wiring binds). Refuses LOUD with the remedy when no
 * statement names an engine root — never a silent skip.
 *
 * @param cfg the endpoint config (the tracked file's parsed shape)
 * @param engineRootOpt explicit engine root (wins over every statement)
 * @param liveRoot explicit overlay value — the wall seam; omitted
 *   reads the machine's engines.comfyui.live_root (engineLiveRoot)
 * @returns {engineRoot, storeRoot} for {@link writeByoExtraPaths}
 */
export function resolveByoAttach(cfg: EndpointConfig,
    engineRootOpt?: string, liveRoot?: string):
    { engineRoot: string; storeRoot: string } {
  const stated = rootStr(String((cfg as Record<string, unknown>)
    ["engine_root"] ?? ""));
  const live = liveRoot ?? engineLiveRoot(cfg);
  const engineRoot = rootStr(engineRootOpt ?? "") || stated || live;
  if (engineRoot === "") {
    throw new Error(
      "[byo-attach] no engine root to attach — name the ComfyUI tree " +
      "in the endpoint config (\"engine_root\": \"/path/to/ComfyUI\") " +
      "or the machine overlay (data/inference.local.json " +
      "engines.comfyui.live_root), or pass it explicitly; never guessed");
  }
  return { engineRoot, storeRoot: boundModelFolders(cfg).download_path };
}

/** One folder's visibility verdict from the running engine. */
export interface StoreFolderProbe {
  /** The registered folder name (the yaml key). */
  folder: string;
  /** The engine answered GET /models/<folder> with a listing. */
  registered: boolean;
  /** The engine's filename list for the folder (all search paths). */
  files: string[];
  /** Filenames sampled from the store's own subdir (empty when the
   *  store dir is absent or empty — the visibility then rests on
   *  registration alone). */
  storeFiles: string[];
  /** Registered AND at least one store file appears in the engine's
   *  listing (vacuously true when the store subdir carries no files).
   *  This is the unlink verdict: an unlinked store never shows its
   *  files in the engine's listing. */
  visible: boolean;
}

/**
 * Ask the RUNNING engine whether the store's folders are visible —
 * read-only GET /models/<folder> per mapped folder, the estate's own
 * in-process engine transport (fetch + abort timeout; never a POST,
 * never a restart). A folder the engine does not register answers
 * 404; a registered folder answers its filename union, and the
 * store's own files must appear there for the link to count. A
 * transport failure (engine unreachable) THROWS — an unreachable
 * engine is not an unlinked store, and the two verdicts must not
 * merge.
 *
 * @param url the engine base URL
 * @param folders the {folder: store subdir} map (byoFolderMap shape)
 * @param opts storeRoot to sample store files from; timeoutMs per probe
 * @returns one verdict per folder, sorted by folder name
 */
export async function probeStoreFolders(url: string,
    folders: Record<string, string>,
    opts: { storeRoot?: string; timeoutMs?: number } = {}):
    Promise<StoreFolderProbe[]> {
  const timeoutMs = opts.timeoutMs ?? 5000;
  const base = url.replace(/\/+$/, "");
  const out: StoreFolderProbe[] = [];
  for (const folder of Object.keys(folders).sort()) {
    const sub = String(folders[folder] ?? "").trim()
      .replace(/^\/+|\/+$/g, "") || folder;
    const storeFiles: string[] = [];
    if (opts.storeRoot !== undefined) {
      const storeDir = join(opts.storeRoot, sub);
      if (existsSync(storeDir)) {
        try {
          storeFiles.push(...readdirSync(storeDir)
            .filter((f) => !f.startsWith("."))
            .sort().slice(0, 8));
        } catch {
          /* unreadable store dir: the sample stays empty and the
             visibility rests on registration alone */
        }
      }
    }
    const target = base + "/models/" + encodeURIComponent(folder);
    let status: number;
    let body: string;
    try {
      const response = await fetch(target,
        { signal: AbortSignal.timeout(timeoutMs) });
      status = response.status;
      body = await response.text();
    } catch (exc: unknown) {
      const err = exc as Error;
      throw new Error(
        "engine unreachable at " + target + " (" + err.name + ": " +
        err.message + ") — start the engine first; an unreachable " +
        "engine is a distinct verdict from an unlinked store");
    }
    const files: string[] = [];
    if (status === 200) {
      try {
        const parsed: unknown = JSON.parse(body);
        if (Array.isArray(parsed)) {
          files.push(...parsed.filter((f): f is string => typeof f === "string"));
        }
      } catch {
        /* non-JSON 200 body: an unreadable listing — registration
           holds, visibility rests on the sample being empty */
      }
    }
    const hit = storeFiles.some((f) => files.includes(f));
    out.push({
      folder,
      registered: status === 200,
      files,
      storeFiles,
      visible: status === 200 && (storeFiles.length === 0 || hit),
    });
  }
  return out;
}
