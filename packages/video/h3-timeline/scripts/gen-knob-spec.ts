/**
 * gen-knob-spec — BUILD-TIME schema walk for the call-knob fold.
 *
 * WHY THIS EXISTS (2026-09-15, the operator's freehand conviction):
 * the knob fold must render from THE CARD'S OWN CARRIER (the same
 * schemastery declaration the served params-spec walks) — but the
 * client-bundle purity gate rightly refuses runtime schemastery in
 * the browser face. The lawful shape is the repo's established
 * generated+gated pattern (ledger-sync R5, goldens): this script
 * walks the carrier SERVER-SIDE and emits a PURE-DATA module the
 * client inlines; tests/knob-spec-freshness walks again and fails
 * the build on drift. One truth (card.ts), two projections.
 *
 * The h3_ key map is mechanical (LayerA spelling, card.ts SLA block:
 * "the h3_ prefix is the studio's LayerA spelling, never the card's").
 * Knobs the carrier does not declare ride CARRIER_GAP — the NAMED
 * debt (declare them on the carrier in a make-card stroke), never a
 * silent hand list.
 */
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { carrier, BOARDED } from "../src/card.ts"
import { emitParamsSpec } from "@melite/comfyui-cordis/params-emit"
import { KNOB_ORDER } from "../src/ui/studio/docModel.ts"

type Face = { type: "number" | "integer" | "boolean" | "string"; label: string; enum?: string[] }

const schemaKey = (knob: string): string =>
  knob === "sampling_steps" ? "steps" : knob.startsWith("h3_") ? knob.slice(3) : knob

const CARRIER_GAP: Record<string, Face> = {
  denoise: { type: "number", label: "Denoise" },
  sampler: { type: "string", label: "Sampler", enum: ["euler", "euler_cfg_pp", "euler_ancestral", "dpmpp_2m", "dpmpp_2m_sde", "heun"] },
  scheduler: { type: "string", label: "Scheduler", enum: ["simple", "beta", "linear_quadratic", "normal", "sgm_uniform", "karras", "exponential", "kl_optimal", "ddim_uniform"] },
  interpolate_model: { type: "string", label: "Interp model", enum: ["film_net_fp32.pt"] },
  interpolate_multiplier: { type: "integer", label: "Interp multiplier" },
}

const SPEC = emitParamsSpec(carrier as never, BOARDED)
const out: Record<string, Face> = {}
const gapKeys: string[] = []

for (const knob of KNOB_ORDER) {
  const node = SPEC[schemaKey(knob)]
  if (node) {
    // strip the emitter's range suffix ("Steps (min: 4, max: 30)") —
    // the label stays the declaration's own word; range truth rides
    // the schema, the tooltip can quote it.
    const face: Face = { type: node.type, label: (node.description ?? knob).replace(/\s*\(min:.*\)\s*$/, "").trim() }
    if (Array.isArray(node.enum) && node.enum.length > 0) face.enum = node.enum.map(String)
    out[knob] = face
  } else if (CARRIER_GAP[knob]) {
    out[knob] = CARRIER_GAP[knob]
    gapKeys.push(knob)
  } else {
    throw new Error(`gen-knob-spec: knob "${knob}" has no carrier row and no CARRIER_GAP entry — declare it (card.ts) or gap it, never drop it`)
  }
}

const cardSha = createHash("sha256").update(readFileSync(new URL("../src/card.ts", import.meta.url))).digest("hex").slice(0, 16)

const body = `// GENERATED by scripts/gen-knob-spec.ts — DO NOT EDIT BY HAND.
// Source of truth: src/card.ts (carrier, sha16 ${cardSha}); regenerate with
// \`npx tsx scripts/gen-knob-spec.ts\`. Freshness gate: tests/knob-spec-freshness.spec.ts
// re-walks the carrier and fails the build on drift.
// Carrier-absent knobs (the named debt, declare on the carrier next
// make-card stroke): ${gapKeys.join(", ") || "none"}
export type KnobFace = { type: "number" | "integer" | "boolean" | "string"; label: string; enum?: string[] }
export const KNOB_SPEC: Record<string, KnobFace> = ${JSON.stringify(out, null, 2)}
export const CARD_SHA16 = "${cardSha}"
export const CARRIER_GAP_KEYS: string[] = ${JSON.stringify(gapKeys)}
`

writeFileSync(new URL("../src/ui/studio/knob-spec.gen.ts", import.meta.url), body)
console.log(`gen-knob-spec: ${Object.keys(out).length} knobs (${gapKeys.length} carrier-gap: ${gapKeys.join(", ") || "none"}) — card.ts ${cardSha}`)
