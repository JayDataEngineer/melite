"""Card lifecycle suite — real-world card coverage (2026-08-31).

The chaos suite breaks the queue on purpose; this suite walks the path
a REAL card takes through the system, the one that bit us in prod when
no test looked at it:

    card birth (draft door) -> run WITH ARTIFACTS (real ffmpeg mux)
    -> write-back into the card -> artifact door serves the bytes
    -> history grows across runs -> runtime corruption heals on click
    -> crash mid-run recovers the card's run -> stop leaves a valid card

Every gap below was a real prod failure or a real near-miss:
  - every hermetic run used to END IN ERROR, so the write-back's
    empty-artifact path shipped uninitialized heap into cards while
    all tests stayed green ("assetUrls":[X\x04], draft-timeline-h3);
  - the artifact door (/editor/assets/runs/...) was never fetched by
    a test — it is what the DSH media sidebar rides;
  - the lint healed cards only at BOOT: a mid-session corruption
    kept the click dead until a restart;
  - long history (>8KB) hit a fixed-buffer clamp and cut rows
    mid-string — the original dead-card bug.
"""
