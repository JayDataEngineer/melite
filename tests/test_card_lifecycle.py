def wait_for(fn, timeout, what):
    deadline = time.time() + timeout
    last = None
    while time.time() < deadline:
        last = fn()
        if last:
            return last
        time.sleep(0.15)
    raise AssertionError("timeout waiting for %s (last=%r)" % (what, last))


def free_port():
    s = socket.socket()
    s.bind(("127.0.0.1", 0))
    p = s.getsockname()[1]
    s.close()
    return p


# ---------------- the fake comfy that SUCCEEDS ----------------
# History entries carry 2 frame images + 1 audio -> the comfy plugin
# muxes a REAL mp4 with ffmpeg and emits video_0 -> the runner persists
# <node_id>_video_0.mp4 in the run dir -> the write-back lists it in the
# card. /view serves REAL media bytes (generated by ffmpeg at suite
# start — fake magic-bytes fail ffmpeg's decoder and the mux) so the
# artifact door can be byte-compared downstream.
PNG = b""
WAV = b""
VIEW_BYTES = {}          # filename -> bytes
OK_HIST = {}             # prompt_id -> history body
OK_SEQ = [0]


def build_real_media():
    """real, tiny, decodable media via the system ffmpeg"""
    global PNG, WAV
    d = "/tmp/lc_media_%d" % os.getpid()
    os.makedirs(d, exist_ok=True)
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error",
                    "-f", "lavfi", "-i", "color=c=red:s=64x48:d=0.2",
                    "-r", "24", os.path.join(d, "f%05d.png")],
                   check=True, capture_output=True)
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error",
                    "-f", "lavfi", "-i", "sine=frequency=440:duration=0.3",
                    os.path.join(d, "a.wav")],
                   check=True, capture_output=True)
    PNG = open(os.path.join(d, "f00001.png"), "rb").read()
    WAV = open(os.path.join(d, "a.wav"), "rb").read()
    shutil.rmtree(d, ignore_errors=True)


class OkComfy(BaseHTTPRequestHandler):
    def _reply(self, code, body=b"{}", ctype="application/json"):
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("X-Melite-Test-Fake", "1")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_POST(self):
        n = int(self.headers.get("Content-Length", 0) or 0)
        self.rfile.read(n)
        if self.path == "/ok/prompt":
            OK_SEQ[0] += 1
            pid = "ok-%04d" % OK_SEQ[0]
            # two frames + one audio for the muxer
            files = []
            for i, (fname, blob) in enumerate(
                    (("f%05d.png" % i, PNG) for i in range(2))):
                VIEW_BYTES[pid + "/" + fname] = blob
                files.append((fname, blob))
            VIEW_BYTES[pid + "/a.wav"] = WAV
            hist = {
                pid: {
                    "status": {"completed": True,
                               "status_str": "success"},
                    "outputs": {
                        "n%d" % i: {"images": [
                            {"filename": fname, "subfolder": "",
                             "type": "output"}]}
                        for i, (fname, _) in enumerate(files)
                    } | {"na": {"audio": [
                        {"filename": "a.wav", "subfolder": "",
                         "type": "output"}]}},
                }
            }
            body = json.dumps(hist).encode()
            OK_HIST[pid] = body
            self._reply(200, json.dumps({"prompt_id": pid}).encode())
            return
        self._reply(404)

    def do_GET(self):
        if self.path == "/object_info":
            wf = os.path.join(HERE, os.pardir, "pipelines",
                              "sprite-sheet", "workflow.json")
            try:
                graph = json.load(open(wf))
                classes = {v.get("class_type", "?"): {}
                           for v in graph.values()
                           if isinstance(v, dict)}
            except Exception:
                classes = {}
            self._reply(200, json.dumps(classes).encode())
            return
        if self.path.startswith("/ok/history/"):
            pid = self.path.rsplit("/", 1)[-1]
            self._reply(200, OK_HIST.get(pid, b"{}"))
            return
        if self.path.startswith("/ok/view"):
            m = re.search(r"filename=([^&]+)", self.path)
            if m:
                # every prompt shares the same frame names; find the
                # freshest bytes for the basename
                base = m.group(1)
                for k, v in VIEW_BYTES.items():
                    if k.endswith("/" + base):
                        self._reply(200, v,
                                    ctype="image/png"
                                    if base.endswith(".png")
                                    else "audio/wav")
                        return
            self._reply(404)
            return
        self._reply(404)

    def log_message(self, *a):
        pass


# never-completing comfy (hold): for stop + crash checks
class HoldComfy(BaseHTTPRequestHandler):
    def _reply(self, code, body=b"{}"):
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        # (leak-gate contract, fixed 2026-09-02) every test fake must
        # prove itself: the sandboxed gateway probes /object_info and
        # refuses to submit without this header. HoldComfy never
        # carried it — L8's crash-recovery run died at the gate the
        # instant it resurrected ("did not prove itself a test fake"),
        # the queue read 0/0 and the test timed out.
        self.send_header("X-Melite-Test-Fake", "1")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_POST(self):
        n = int(self.headers.get("Content-Length", 0) or 0)
        self.rfile.read(n)
        self._reply(200, b'{"prompt_id":"hold-0001"}')

    def do_GET(self):
        if self.path == "/object_info":
            wf = os.path.join(HERE, os.pardir, "pipelines",
                              "sprite-sheet", "workflow.json")
            try:
                graph = json.load(open(wf))
                classes = {v.get("class_type", "?"): {}
                           for v in graph.values()
                           if isinstance(v, dict)}
            except Exception:
                classes = {}
            self._reply(200, json.dumps(classes).encode())
            return
        self._reply(200, b"{}")

    def log_message(self, *a):
        pass


class Api:
    def __init__(self, port):
        self.port = port

    def _req(self, method, path, body=None, raw=False):
        import http.client
        data = None
        if body is not None:
            data = (json.dumps(body) if isinstance(body, (dict, list))
                    else body)
        try:
            c = http.client.HTTPConnection("127.0.0.1", self.port,
                                           timeout=10)
            c.request(method, path, body=data,
                      headers={"Content-Type": "application/json"})
            r = c.getresponse()
            payload = r.read()
            code = r.status
            c.close()
        except OSError:
            return -1, (b"" if raw else "")
        return code, (payload if raw else payload.decode("utf-8",
                                                         "replace"))

    def get(self, path, raw=False):
        code, body = self._req("GET", path, raw=raw)
        return code, body

    def post(self, path, body):
        return self._req("POST", path, body)

    def queue(self):
        code, body = self.get("/v1/queue")
        try:
            return json.loads(body)
        except ValueError:
            return {"queued": -1, "running": -1}

    def status(self, rid):
        code, body = self.get("/v1/pipelines/status/" + rid)
        if code != 200:
            return None
        try:
            return json.loads(body)
        except ValueError:
            return None

    def stop(self, rid):
        return self.post("/v1/pipelines/stop/" + rid, "{}")


def terminal(st):
    if not st:
        return None
    s = st.get("status")
    return s if s in ("done", "completed", "error", "stopped",
                      "failed") else None


def kill_hard(pid):
    try:
        os.kill(pid, signal.SIGKILL)
    except ProcessLookupError:
        pass
    try:
        os.waitpid(pid, 0)
    except ChildProcessError:
        pass


def boot_gateway(port, log):
    # (leak gate) every booted gateway carries the test sandbox: the
    # only legal endpoint is this scratch config — never the on-disk
    # default that points at the REAL ComfyUI. Runs that need comfy
    # pass their own inline server_url (the fakes above).
    cfg = "/tmp/cardlife_endpoint_%d.json" % port
    with open(cfg, "w") as f:
        json.dump({"url": "http://127.0.0.1:9"}, f)
    genv = dict(os.environ)
    genv["COMFYUI_ENDPOINT_CONFIG"] = cfg
    genv["INFERENCE_TEST_SANDBOX"] = "1"
    p = subprocess.Popen(
        ["./inference_cli", "serve", "--port", str(port)],
        cwd=os.path.join(HERE, os.pardir, "build"),
        stdin=subprocess.DEVNULL, stdout=open(log, "ab"),
        stderr=subprocess.STDOUT, start_new_session=True, env=genv)
    return p


