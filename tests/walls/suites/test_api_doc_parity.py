def _strip_comments(text: str) -> str:
    """Remove // and /* */ comments outside string literals."""
    out: list[str] = []
    i, n = 0, len(text)
    in_str = False
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            if c == "\\":
                if i + 1 < n:
                    out.append(text[i + 1])
                    i += 1
            elif c == '"':
                in_str = False
            i += 1
            continue
        if c == '"':
            in_str = True
            out.append(c)
            i += 1
        elif c == "/" and i + 1 < n and text[i + 1] == "/":
            while i < n and text[i] != "\n":
                i += 1
        elif c == "/" and i + 1 < n and text[i + 1] == "*":
            i += 2
            while i + 1 < n and not (text[i] == "*" and text[i + 1] == "/"):
                i += 1
            i += 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def _split_top_objects(array_body: str) -> list[str]:
    """Top-level {...} spans of an array literal (string-aware)."""
    objs: list[str] = []
    i, n = 0, len(array_body)
    while i < n:
        if array_body[i] != "{":
            i += 1
            continue
        depth = 0
        in_str = False
        j = i
        while j < n:
            c = array_body[j]
            if in_str:
                if c == "\\":
                    j += 1
                elif c == '"':
                    in_str = False
            elif c == '"':
                in_str = True
            elif c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    objs.append(array_body[i:j + 1])
                    break
            j += 1
        i = j + 1
    return objs


def _str_field(obj: str, name: str) -> str:
    m = re.search(r"%s\s*:\s*\"((?:[^\"\\]|\\.)*)\"" % re.escape(name), obj)
    if m is None:
        raise ValueError("row has no %r string field" % name)
    return json.loads('"%s"' % m.group(1))


def _ts_rows() -> list[dict[str, object]]:
    """The authored table, parsed with stdlib only (the same
    rigid-literal reader the inverted mirror wall owns; this wall
    reads only the surface it pins)."""
    text = ROUTES_TS.read_text(encoding="utf-8")
    anchor = text.index("export const ROUTES")
    body = _strip_comments(text[anchor:])
    lb, rb = body.index("["), body.rindex("]")
    rows = []
    for obj in _split_top_objects(body[lb:rb]):
        rows.append({
            "method": _str_field(obj, "method"),
            "path": _str_field(obj, "path"),
            "template": _str_field(obj, "template"),
            "group": _str_field(obj, "group"),
            "ws": "ws: true" in obj,
        })
    return rows


def _label(row: dict[str, object]) -> str:
    if row["ws"]:
        return "WS"
    method = str(row["method"])
    if method == "*":
        return "ANY"
    return method.replace("|", "/")


def _table_surface() -> set[tuple[str, str]]:
    """(method-label, path-or-template) for every route row."""
    out = set()
    for row in _ts_rows():
        out.add((_label(row), str(row["template"] or row["path"])))
    return out


def _doc_surface() -> set[tuple[str, str]]:
    """Parse the generated markdown tables back into the same shape."""
    rows = set()
    for m in re.finditer(
            r"^\|\s*([A-Z/]+)\s*\|\s*`([^`]+)`\s*\|", DOC.read_text(), re.M):
        rows.add((m.group(1), m.group(2)))
    return rows


def _spec_surface() -> set[tuple[str, str]]:
    """(method, path) pairs from the openapi yaml (no yaml dep needed:
    the generator emits a flat, greppable layout)."""
    text = SPEC.read_text()
    out = set()
    path = None
    verb = None
    for line in text.splitlines():
        pm = re.match(r"^  (\S+):$", line)
        if pm:
            path, verb = pm.group(1), None
            continue
        vm = re.match(r"^    (get|post|delete|put|patch):$", line)
        if vm and path:
            verb = vm.group(1).upper()
            out.add((verb, path))
    # WS rows: the spec marks them in the summary; recover the label
    for m in re.finditer(r'^  (\S+):\n(?:.*\n)*?    get:\n      summary: ".*\[websocket', SPEC.read_text()):
        out.discard(("GET", m.group(1)))
        out.add(("WS", m.group(1)))
    return out


