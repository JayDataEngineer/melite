"""test_api_doc_parity.py — the wire-surface SSOT wall.

Three restatements of the gateway's HTTP surface must agree, always:
  1. the ROUTE TABLE (py/gateway.py ROUTES — the dispatch authority)
  2. docs/gateway/endpoints.md (generated by tools/gen_api_docs.py)
  3. docs/gateway/openapi.yaml  (generated by tools/gen_api_docs.py)

A route without a doc row, a doc row without a route, a spec path
without a route — all drift, all refused here. The generator also
exposes --check (byte compare) which this wall runs so a stale
regeneration cannot slip through.

Response BODIES are the goldens' authority (tests/golden_http/) — this
wall pins the PATH LIST only. Run: pytest tests/walls/suites/
test_api_doc_parity.py (native pytest; no gateway boot needed).
"""
import re
import subprocess
import sys
from pathlib import Path

import pytest

from _anchor import REPO  # noqa: F401  (path anchor via tests/_bootstrap)

import gateway  # noqa: E402  (path anchored by _anchor)

DOC = REPO / "docs" / "gateway" / "endpoints.md"
SPEC = REPO / "docs" / "gateway" / "openapi.yaml"


def _table_surface() -> set[tuple[str, str]]:
    """(method-label, path-or-template) for every route row."""
    out = set()
    for row in gateway.ROUTES:
        label = ("WS" if row.ws else
                 ("ANY" if row.method == "*" else row.method.replace("|", "/")))
        out.add((label, row.template or row.path))
    return out


def _doc_surface() -> set[tuple[str, str]]:
    """Parse the generated markdown tables back into the same shape."""
    rows = set()
    for m in re.finditer(
            r"^\|\s*([A-Z/]+)\s*\|\s*`([^`]+)`\s*\|", DOC.read_text(), re.M):
        rows.add((m.group(1), m.group(2)))
    return rows


def _spec_surface() -> set[tuple[str, str]]:
    """(method, path) pairs from the openapi yaml (no yaml dep needed:
    the generator emits a flat, greppable layout)."""
    text = SPEC.read_text()
    out = set()
    path = None
    verb = None
    for line in text.splitlines():
        pm = re.match(r"^  (\S+):$", line)
        if pm:
            path, verb = pm.group(1), None
            continue
        vm = re.match(r"^    (get|post|delete|put|patch):$", line)
        if vm and path:
            verb = vm.group(1).upper()
            out.add((verb, path))
    # WS rows: the spec marks them in the summary; recover the label
    for m in re.finditer(r'^  (\S+):\n(?:.*\n)*?    get:\n      summary: ".*\[websocket', SPEC.read_text()):
        out.discard(("GET", m.group(1)))
        out.add(("WS", m.group(1)))
    return out


