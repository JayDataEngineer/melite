"""test_api_doc_parity.py — the wire-surface SSOT wall.

Three restatements of the gateway's HTTP surface must agree, always:
  1. the ROUTE TABLE (py/gateway.py ROUTES — the dispatch authority)
  2. docs/gateway/endpoints.md (generated by tools/gen_api_docs.py)
  3. docs/gateway/openapi.yaml  (generated by tools/gen_api_docs.py)

A route without a doc row, a doc row without a route, a spec path
without a route — all drift, all refused here. The generator also
exposes --check (byte compare) which this wall runs so a stale
regeneration cannot slip through.

Response BODIES are the goldens' authority (tests/golden_http/) — this
wall pins the PATH LIST only. Run: pytest tests/walls/suites/
test_api_doc_parity.py (native pytest; no gateway boot needed).
"""
import re
import subprocess
import sys
from pathlib import Path

import pytest

from _anchor import REPO  # noqa: F401  (path anchor via tests/_bootstrap)

import gateway  # noqa: E402  (path anchored by _anchor)

DOC = REPO / "docs" / "gateway" / "endpoints.md"
SPEC = REPO / "docs" / "gateway" / "openapi.yaml"


def _table_surface():
    """(method-label, path-or-template) for every route row."""
    out = set()
    for row in gateway.ROUTES:
        label = ("WS" if row.ws else
                 ("ANY" if row.method == "*" else row.method.replace("|", "/")))
        out.add((label, row.template or row.path))
    return out


def _doc_surface():
    """Parse the generated markdown tables back into the same shape."""
    rows = set()
    for m in re.finditer(
            r"^\|\s*([A-Z/]+)\s*\|\s*`([^`]+)`\s*\|", DOC.read_text(), re.M):
        rows.add((m.group(1), m.group(2)))
    return rows


def _spec_surface():
    """(method, path) pairs from the openapi yaml (no yaml dep needed:
    the generator emits a flat, greppable layout)."""
    text = SPEC.read_text()
    out = set()
    path = None
    verb = None
    for line in text.splitlines():
        pm = re.match(r"^  (\S+):$", line)
        if pm:
            path, verb = pm.group(1), None
            continue
        vm = re.match(r"^    (get|post|delete|put|patch):$", line)
        if vm and path:
            verb = vm.group(1).upper()
            out.add((verb, path))
    # WS rows: the spec marks them in the summary; recover the label
    for m in re.finditer(r'^  (\S+):\n(?:.*\n)*?    get:\n      summary: ".*\[websocket', SPEC.read_text()):
        out.discard(("GET", m.group(1)))
        out.add(("WS", m.group(1)))
    return out


def test_route_table_nonempty_and_grouped():
    # yaml+resume retirement 2026-09-05: 7 yaml doors + 1 resume = 38
    assert len(gateway.ROUTES) == 38
    groups = {r.group for r in gateway.ROUTES}
    assert len(groups) >= 6
    for g in groups:
        assert g and g.strip() == g


def test_doc_matches_table():
    missing = _table_surface() - _doc_surface()
    extra = _doc_surface() - _table_surface()
    assert not missing, "routes missing from endpoints.md: %s" % sorted(missing)
    assert not extra, "doc rows with no route: %s" % sorted(extra)


def test_spec_matches_table():
    spec = _spec_surface()
    for label, tmpl in _table_surface():
        if label in ("WS", "ANY"):
            continue          # ws/any collapse in the spec; covered below
        path = tmpl.split("?")[0]
        for verb in label.split("/"):
            assert (verb, path) in spec, \
                "openapi.yaml missing %s %s" % (verb, path)


def test_ws_rows_present_in_spec():
    text = SPEC.read_text()
    for row in gateway.ROUTES:
        if row.ws:
            assert "[websocket" in text
            break


def test_generator_check_mode_clean():
    """--check must pass: the on-disk files equal the table's output."""
    r = subprocess.run(
        [sys.executable, str(REPO / "tools" / "gen_api_docs.py"), "--check"],
        capture_output=True, text=True, timeout=60)
    assert r.returncode == 0, \
        "stale generated docs — run: .venv/bin/python tools/gen_api_docs.py\n%s" % r.stdout


def test_no_retired_start_shapes_in_docs():
    """The yaml START door retired 2026-09-04: docs must not teach it.
    Provenance docs (audits, logs, the retirement design record itself)
    legitimately MENTION the dead door — allowlisted by path."""
    provenance = {
        "audits", "migration-log.md", "py-gateway-switchover.md",
        "flows.md",   # docs/queue/flows.md — the retirement design record
    }
    banned = []
    for doc in REPO.glob("docs/**/*.md"):
        try:
            text = doc.read_text()
        except OSError:
            continue
        if doc.parent.name in provenance or doc.name in provenance:
            continue
        for m in re.finditer(
                r"/v1/flows/start[^\n]{0,80}\{(?:[^}\n]*['\"])?yaml['\"]", text):
            banned.append("%s: %s" % (doc.name, m.group(0)[:90]))
        for m in re.finditer(r"\{yaml:\s*['\"]?[\w-]+", text):
            banned.append("%s: %s" % (doc.name, m.group(0)[:90]))
        for m in re.finditer(r'"yaml"\s*:', text):
            banned.append("%s: %s" % (doc.name, m.group(0)[:90]))
    assert not banned, "docs teach the retired {yaml:} start shape:\n%s" % \
        "\n".join(banned)
