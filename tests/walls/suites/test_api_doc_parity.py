def test_no_retired_start_shapes_in_docs() -> None:
    """The yaml START door retired 2026-09-04: docs must not teach it.
    Provenance docs (audits, logs, the retirement design record itself)
    legitimately MENTION the dead door — allowlisted by path."""
    provenance = {
        "audits", "migration-log.md", "py-gateway-switchover.md",
        "flows.md",   # docs/queue/flows.md — the retirement design record
        # the 2026-09-07 review quotes the retired shapes as FINDING
        # EVIDENCE (H3) — citations, not teachings
        "declarative-pattern-review.md",
    }
    banned = []
    for doc in REPO.glob("docs/**/*.md"):
        try:
            text = doc.read_text()
        except OSError:
            continue
        if doc.parent.name in provenance or doc.name in provenance:
            continue
        for m in re.finditer(
                r"/v1/flows/start[^\n]{0,80}\{(?:[^}\n]*['\"])?yaml['\"]", text):
            banned.append("%s: %s" % (doc.name, m.group(0)[:90]))
        for m in re.finditer(r"\{yaml:\s*['\"]?[\w-]+", text):
            banned.append("%s: %s" % (doc.name, m.group(0)[:90]))
        for m in re.finditer(r'"yaml"\s*:', text):
            banned.append("%s: %s" % (doc.name, m.group(0)[:90]))
    assert not banned, "docs teach the retired {yaml:} start shape:\n%s" % \
        "\n".join(banned)
