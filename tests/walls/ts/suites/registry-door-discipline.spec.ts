// registry-door-discipline.spec.ts — THE REGISTRY DOOR'S ESTATE WALL
// (2026-10-18, the registry door landing): every melite pack is
// published live on registry.comfy.org under publisher
// `data-engineer`, and the pack repos auto-publish on pyproject
// version bumps. The registry versions are IMMUTABLE — a re-publish
// of a taken version fails its workflow — so this wall holds the
// two laws the door owes the estate:
// 1. NEVER REGRESS: each vendor pack's pyproject version is
//    greater-than-or-equal to the version already published (the
//    snapshot below; bump the row when a publish lands).
// 2. ONE DEP SET, TWO DOORS: requirements.txt (what
//    ComfyUI-Manager pip-installs on the git-url door) and
//    [project].dependencies (what the registry action installs)
//    declare the same set — a dep cured into one file but not the
//    other serves a different environment per door.
// The id arm pins the registry identity: PublisherId is
// `data-engineer`, the Repository URL points at the owning repo,
// and the node id matches the ROSTER (the FastVAE variant carries
// its own melite-distinct id — the upstream name is owned by the
// starsfriday publisher, 2026-10-18).
import { describe, expect, it } from "vitest";
import { readFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(__dirname, "..", "..", "..", "..");
const VENDOR = join(ROOT, "vendor", "comfyui_extensions");

/** repo directory → [registry node id, published version]. */
const ROSTER: Record<string, [string, string]> = {
  "ComfyUI-MiniMax-H3-MotionCache-FastVAE": [
    "melite-minimax-h3-motioncache-fastvae",
    "1.0.0",
  ],
  "comfyui-minimax-h3-timeline-director": [
    "comfyui-minimax-h3-timeline-director",
    "0.8.0",
  ],
  "melite-audio-nodes": ["melite-audio-nodes", "0.1.0"],
  "melite-autorig-nodes": ["melite-autorig-nodes", "0.1.0"],
  "melite-kimodo-nodes": ["melite-kimodo-nodes", "0.1.0"],
  "melite-model-base": ["melite-model-base", "1.0.0"],
  "melite-poser-nodes": ["melite-poser-nodes", "0.1.0"],
  // melite-sfx-nodes + melite-tts-nodes are NOT here: removed from
  // the estate 2026-11-10 (the one-audio-pack consolidation — every
  // Audiocore* class lives in melite-audio-nodes; the carves were
  // byte-identical duplicates). Published-dormant like unity above:
  // versions are immutable, no vendored repo left to discipline.
  // melite-unity-nodes is NOT here: removed from the estate
  // 2026-10-18 (operator ruling, audit 008 M15 — the M12 shape).
  // Its registry node data-engineer/melite-unity-nodes 0.1.0 stays
  // published-dormant (versions are immutable); it has no vendored
  // repo to discipline anymore.
  "melite-utility-nodes": ["melite-utility-nodes", "0.1.0"],
};

/** Parse a pyproject.toml [project] block for the fields this wall
 *  pins. The packs' pyprojects are generated by one template (the
 *  registry-door commits), so a line-oriented read is exact. */
function readProject(repo: string): Record<string, string> {
  const text = readFileSync(join(VENDOR, repo, "pyproject.toml"), "utf8");
  const out: Record<string, string> = {};
  for (const line of text.split("\n")) {
    const m = line.match(/^([A-Za-z_]+)\s*=\s*"(.*)"\s*$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

/** The declared dep set from [project].dependencies (TOML string
 *  array, one per line in the template). */
function readPyprojectDeps(repo: string): string[] {
  const text = readFileSync(join(VENDOR, repo, "pyproject.toml"), "utf8");
  const out: string[] = [];
  for (const line of text.split("\n")) {
    const m = line.match(/^\s*"([^"]+)",?\s*$/);
    if (m) out.push(m[1]);
  }
  return out;
}

/** The declared dep set from requirements.txt — comments and blank
 *  lines are prose, everything else declares a package. A pack with
 *  no requirements.txt declares zero deps (model-base's law: the
 *  base env carries it). */
function readRequirementsDeps(repo: string): string[] {
  const path = join(VENDOR, repo, "requirements.txt");
  if (!existsSync(path)) return [];
  const text = readFileSync(path, "utf8");
  return text
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l.length > 0 && !l.startsWith("#"));
}

/** a >= b for dotted numeric versions (major.minor.patch). */
function versionAtLeast(a: string, b: string): boolean {
  const pa = a.split(".").map(Number);
  const pb = b.split(".").map(Number);
  for (let i = 0; i < 3; i += 1) {
    if ((pa[i] ?? 0) > (pb[i] ?? 0)) return true;
    if ((pa[i] ?? 0) < (pb[i] ?? 0)) return false;
  }
  return true;
}

describe("registry door discipline", () => {
  it("every pack carries a roster row — no pack publishes unrostered", () => {
    const repos = Object.keys(ROSTER).sort();
    // 8, not 10 (2026-11-10): melite-unity-nodes left the estate
    // 2026-10-18 (M15 ruling; its registry node stays
    // published-dormant — see the roster comment above),
    // melite-autoremesher-nodes left 2026-10-13 (the autoremesher
    // excision — the pack the owner removed from the system), and
    // melite-sfx-nodes + melite-tts-nodes left 2026-11-10 (the
    // one-audio-pack consolidation; published-dormant, same shape).
    expect(repos).toHaveLength(8);
    for (const repo of repos) {
      expect(readProject(repo).name, repo).toBe(ROSTER[repo][0]);
    }
  });

  it("never regresses a published version", () => {
    for (const [repo, [, published]] of Object.entries(ROSTER)) {
      const version = readProject(repo).version ?? "";
      expect(
        versionAtLeast(version, published),
        `${repo}: pyproject ${version} < published ${published} — the registry refuses a re-publish`,
      ).toBe(true);
    }
  });

  it("one dep set, two doors — requirements.txt equals [project].dependencies", () => {
    for (const repo of Object.keys(ROSTER)) {
      const req = readRequirementsDeps(repo);
      const dep = readPyprojectDeps(repo);
      expect(new Set(dep), `${repo}: doors disagree`).toEqual(new Set(req));
    }
  });

  it("publisher and repository identity hold in every pack", () => {
    for (const repo of Object.keys(ROSTER)) {
      const proj = readProject(repo);
      expect(proj.PublisherId, repo).toBe("data-engineer");
      expect(
        proj.Repository ?? proj.repository,
        repo,
      ).toBe(`https://github.com/JayDataEngineer/${repo}`);
    }
  });
});
