/**
 * LANE COMPACTION PARITY (2026-11-05 — the lane compacts-at-32k burn).
 *
 * THE LAW: the melite-test lane render's compaction doctrine equals the
 * estate's reconciled budget law — no exact-target compaction policy
 * fires below 80% of a patch-declared 200k window, and every
 * compaction-basic block carries its explicit summarizer output cap and
 * its generated policy mirror.
 *
 * THE BURN this wall owns: the lane's operator rows
 * (dev_docs/deployment/studio-lane-rows.yml — the --profile-rows splice
 * source, a verbatim copy of the web profile's rows) froze the 2026-10-08
 * split-brain override `thresholdRatio: 0.16` into 35 policy rows. That
 * ratio was calibrated for the ONE split-brain model whose live pi-ai
 * window was the upstream 1M (0.16 × 1M = 160k = 80% of the 200k cap).
 * The pi-ai adapter merges patch rows over its catalog
 * (`entry.contextWindow ?? base?.contextWindow`, dsh-llm-pi-ai), so every
 * roster-declared model resolves to the operator's 200,000 — and
 * 0.16 × 200,000 = 32,000: the lane's estate agent hit the compactor
 * five turns into a session while the main profile (:3080, generated
 * 0.8 policies) fires at 160,000. The same stale copy also predated the
 * 2026-10-17 per-agent cures: no explicit `maxTokens` (the plugin derives
 * it from headroom → 4096-token truncated checkpoints, the TTFT death)
 * and no mirrored `modelPolicies` (a never-fire on genuinely split-brain
 * models). The fix re-synced every compaction-basic block from the web
 * profile's generated truth; this wall keeps the copy honest.
 *
 * TRUTH HOMES: dev_docs/deployment/studio-lane-rows.yml (the render
 * input — the lane's own source of truth per its header law) and, when
 * this machine has rendered the lane, the rendered
 * ~/.dsh-dev/profiles/melite-test/cordis.patch.yml bytes the boot reads.
 * dev_docs is untracked (the fresh-clone law): the suite NAMED-skips
 * when the rows file is absent, exactly like contracts-registry.spec.ts.
 *
 * Run: npx vitest run tests/walls/ts/suites/lane-compaction-parity.spec.ts
 */
import { describe, it, expect } from "vitest";
import { existsSync, readFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "../../../..");
const ROWS = join(ROOT, "dev_docs/deployment/studio-lane-rows.yml");

/** The reconciled budget floor: a 200k-cap roster model must fire at 80%
 *  (160,000). The plugin caps threshold by
 *  min(window × ratio, window − reservedCompletion − headroom), so the
 *  only lawful ratios in estate rows are 0.8 (the floor) and 1.0
 *  (budget-capped at 163,136 — still ≥ the floor). Anything below 0.8 is
 *  an early-fire pin: the burn this wall exists for. */
const RATIO_FLOOR = 0.8;

/** The explicit summarizer output cap (32K = the plugin's own default
 *  constant). Absent, the plugin derives maxTokens from headroomTokens
 *  (4096) and every checkpoint truncates. */
const SUMMARIZER_CAP = "maxTokens: 32768";

const MARKER = "GENERATED by gates/render-compaction-rows.py";

/** Extract every compaction-basic block as {indent, preset, text}.
 *  Block = the `- id: compaction-basic` line through the next sibling
 *  `- id:` line at the same indent, exclusive. preset = the nearest
 *  preceding indent-2 `preset-…` id, "top" for the profile-level row. */
function compactionBlocks(text) {
  const lines = text.split("\n");
  const blocks = [];
  for (let i = 0; i < lines.length; i++) {
    const m = /^(\s*)- id: compaction-basic$/.exec(lines[i]);
    if (!m) continue;
    const pad = m[1];
    let end = lines.length;
    for (let j = i + 1; j < lines.length; j++) {
      if (new RegExp(`^${pad}- id: `).test(lines[j])) { end = j; break; }
      if (lines[j].trim() !== "" && !lines[j].startsWith(pad)) { end = j; break; }
    }
    let preset = "top";
    for (let j = i; j >= 0; j--) {
      const p = /^ {2}- id: (preset-[a-z0-9-]+)$/.exec(lines[j]);
      if (p) { preset = p[1]; break; }
    }
    blocks.push({ indent: pad.length, preset, text: lines.slice(i, end).join("\n") });
  }
  return blocks;
}

const ROWS_PRESENT = existsSync(ROWS);
const rowsText = ROWS_PRESENT ? readFileSync(ROWS, "utf8") : "";
const LANE_PATCH = join(homedir(), ".dsh-dev/profiles/melite-test/cordis.patch.yml");

describe.skipIf(!ROWS_PRESENT)("THE LANE COMPACTION PARITY WALL (the splice source carries the estate's compaction doctrine)", () => {
  it("no exact-target policy fires below the budget floor — the 0.16 split-brain class is dead (ARM 1, the burn)", () => {
    const offenders = [...rowsText.matchAll(/^(\s*)thresholdRatio: ([0-9.]+)$/gm)]
      .filter(([, , v]) => Number(v) < RATIO_FLOOR)
      .map(([, pad, v]) => `${v} (indent ${pad.length})`);
    expect(
      offenders,
      `early-fire compaction ratios in dev_docs/deployment/studio-lane-rows.yml: ${offenders.join(", ")} — a patch-declared 200k model resolves its LIVE window from the roster (dsh-llm-pi-ai merges entry.contextWindow over the pi-ai catalog), so ratio × 200000 IS the fire point; the estate floor is ${RATIO_FLOOR} (glm-5.3-flash: 160000). The 2026-10-08 0.16 override was calibrated for a 1M split-brain window that no roster-declared model has anymore`,
    ).toEqual([]);
  });

  it("the profile-level compactor carries its explicit summarizer cap (ARM 2, the TTFT death)", () => {
    const top = compactionBlocks(rowsText).find((b) => b.indent === 0);
    expect(top, "dev_docs/deployment/studio-lane-rows.yml has no profile-level compaction-basic row").toBeTruthy();
    expect(
      top.text.includes(SUMMARIZER_CAP),
      "the profile-level compaction-basic config omits maxTokens: 32768 — the plugin derives maxTokens from headroomTokens (4096) and every checkpoint truncates (the 2026-10-17 TTFT death: ~60s lost per compaction attempt)",
    ).toBe(true);
  });

  it("every preset-scoped compactor mirrors the cure: cap + generated policy block (ARM 3, the jam class)", () => {
    const presets = compactionBlocks(rowsText).filter((b) => b.indent > 0);
    expect(presets.length, "no preset-scoped compaction-basic blocks found — the rows file lost the preset compaction groups").toBeGreaterThan(0);
    const sick = presets
      .filter((b) => !b.text.includes(SUMMARIZER_CAP) || !b.text.includes("modelPolicies:") || !b.text.includes(MARKER))
      .map((b) => b.preset);
    expect(
      sick,
      `preset compaction-basic blocks missing the 2026-10-17 mirror (explicit maxTokens + generated modelPolicies): ${sick.join(", ")} — an unmirrored preset never-fires on a genuinely split-brain model (the catalog window wins there) and truncates its checkpoints at the derived 4096 cap`,
    ).toEqual([]);
  });

  it("the refuted no-mirror stance stays dead (ARM 4 — the doctrine flip is not re-litigable in rows)", () => {
    expect(
      /mirrored here \(an override calibrated/.test(rowsText),
      "the refuted 2026-10-13 comment ('exact-target overrides are deliberately NOT mirrored here…') returned to dev_docs/deployment/studio-lane-rows.yml — the stance was REFUTED 2026-10-17 (a never-fire kills sessions); the cured comment QUOTES the phrase, this literal is the pre-refutation wording only",
    ).toBe(false);
  });
});

describe.skipIf(!ROWS_PRESENT || !existsSync(LANE_PATCH))("THE RENDERED-BYTES ARM (the boot reads the patch, not the rows)", () => {
  it("the rendered lane patch carries the same doctrine as the rows it was spliced from (ARM 5, DEPTH — a stale render reds)", () => {
    const patch = readFileSync(LANE_PATCH, "utf8");
    const rowsMarkers = rowsText.split(MARKER).length - 1;
    const patchMarkers = patch.split(MARKER).length - 1;
    const early = [...patch.matchAll(/thresholdRatio: ([0-9.]+)/g)]
      .filter(([, v]) => Number(v) < RATIO_FLOOR)
      .map(([, v]) => v);
    expect(
      early.length === 0 && patchMarkers >= rowsMarkers,
      `~/.dsh-dev/profiles/melite-test/cordis.patch.yml is stale against the rows file (early ratios: ${early.join(", ") || "none"}; generated compaction markers patch=${patchMarkers} rows=${rowsMarkers}) — re-run the render (node packages/harness/provisioner/bin/infer-provision.mjs profile melite-test --dsh-home ~/.dsh-dev --estate-agent-route zai/glm-5.3-flash --profile-rows dev_docs/deployment/studio-lane-rows.yml), then lane-rebuild.sh`,
    ).toBe(true);
  });
});
