// engine-tree-sync.spec.ts — THE ENGINE-TREE SYNC TRIPWIRE
// (audit 016 C4).
//
// THE BURN: the repo pinned the qwen3-tts cure (`transformers==5.20.2`
// in the vendored pack, 2026-11-10) and the SERVING ENGINE ran a
// custom_nodes copy from 2026-10-23 — repo cures never reached the
// engine, and every variant load died on the drifted transformers.
// The repo pins each extension pack twice (the vendor submodule
// gitlink; the nodes.yaml manifest row's ref), and the deployed
// engine trees carry git checkouts of the same packs — nothing
// asserted the two sides agree.
//
// THE TRIPWIRE: for every deployed pack tree, every pack dir that the
// parent repo pins (a vendor gitlink under vendor/comfyui_extensions,
// else a manifest row whose git url basename names the dir) must sit
// at HEAD == that pin AND be clean of uncommitted source drift.
// Bytecode artifacts (__pycache__, *.pyc — tracked upstream in some
// packs and regenerated by every import) are not source drift and do
// not judge. A checkout whose git identity dangles (a hand-copied dir
// whose .git file points into a missing modules dir) cannot be
// verified at all and REDS — unverifiable is the drift class, not a
// pass. STANDS DOWN (skip, not pass) when a tree is absent, so
// consumer machines without a deployed engine never false-red.
import { describe, it } from "vitest";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { basename, join } from "node:path";
import { mergeManifest } from "../../../../packages/engines/comfyui-cordis/scripts/provision-extensions-manifest.ts";
import type { ExtRow } from "../../../../packages/engines/comfyui-cordis/scripts/provision-extensions-manifest.ts";

const REPO = join(import.meta.dirname, "..", "..", "..", "..");
const VENDOR = "vendor/comfyui_extensions";
const MANAGED_TREE = join(REPO, "data", "runtime", "comfyui", "custom_nodes");
// The dev engine tree the audit named, overridable by the machine's
// own endpoint statement (engine_root — the live engine's tree).
const AUDIT_DEV_TREE = "/home/user/tools/comfyui/custom_nodes";

/** Dir-name join key: Manager re-forms clone dir names (case,
 *  separators), so pins and deployed dirs meet on letters+digits
 *  only. */
function norm(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "");
}

/** The parent repo's vendored pack pins, from git itself — never a
 *  frozen roster: mode 160000 rows under vendor/comfyui_extensions. */
function gitlinkPins(): Map<string, string> {
  const r = spawnSync("git", ["ls-files", "--stage", VENDOR],
    { cwd: REPO, encoding: "utf8" });
  assert.equal(r.status, 0,
    "git ls-files failed — the parent repo checkout is malformed");
  const out = new Map<string, string>();
  for (const line of (r.stdout ?? "").split("\n")) {
    if (!line.startsWith("160000")) continue;
    const [meta, path] = line.split("\t");
    out.set(basename(path ?? ""), (meta.split(/\s+/)[1] ?? "").trim());
  }
  return out;
}

/** The manifest rows' pins keyed by the pack's git url basename
 *  (normalized) — the install-time pin Manager checks out. */
function manifestPins(): Map<string, ExtRow> {
  const out = new Map<string, ExtRow>();
  for (const row of mergeManifest(REPO)) {
    if (!row.url) continue;
    const key = norm(basename(String(row.url).replace(/\.git$/, "")));
    if (!out.has(key)) out.set(key, row);
  }
  return out;
}

/** The dev engine tree from the machine's own endpoint statement,
 *  falling back to the audit-named path. */
function devEngineTree(): string {
  const stateHome = join(REPO, "data", "comfyui_endpoint.json");
  if (existsSync(stateHome)) {
    try {
      const root = (JSON.parse(readFileSync(stateHome, "utf8")) as
        Record<string, unknown>)["engine_root"];
      if (typeof root === "string" && root.trim() !== "") {
        return join(root.trim(), "custom_nodes");
      }
    } catch {
      /* unparseable state home: fall through to the audit path — this
         wall judges deployed trees, not the endpoint statement */
    }
  }
  return AUDIT_DEV_TREE;
}

const TREES: readonly [string, string][] = [
  ["the dev engine tree", devEngineTree()],
  ["the managed runtime tree", MANAGED_TREE],
];

const LINKS = gitlinkPins();
const ROWS = manifestPins();
const LINKS_BY_NORM = new Map(
  [...LINKS].map(([name, sha]) => [norm(name), [name, sha] as const]));

/** Bytecode-only status lines are artifacts, not source drift. */
function isBytecode(line: string): boolean {
  return /__pycache__\//.test(line) || /\.pyc$/.test(line);
}

describe("the engine-tree sync tripwire (audit 016 C4: repo cures reach the engine)", () => {
  it("the two pin sources agree for every pack both name", () => {
    const both = [...LINKS].filter(([name]) => ROWS.has(norm(name)));
    assert.ok(
      both.length > 0,
      "no pack carries both a vendor gitlink and a manifest ref — the " +
        "roster shifted and this arm has nothing to judge");
    for (const [name, sha] of both) {
      const ref = ROWS.get(norm(name))?.ref ?? "";
      assert.equal(
        ref, sha,
        `${name}: vendor gitlink ${sha.slice(0, 12)} vs manifest ref ` +
          `${ref.slice(0, 12)} — a pack bump landed on one side only; ` +
          "re-pin deliberately");
    }
  });

  for (const [label, tree] of TREES) {
    const present = existsSync(tree);
    console.log(
      `engine-tree-sync: ${label} ${present ? "present" : "ABSENT"} at ` +
        `${tree}` +
        (present
          ? ""
          : " — STANDS DOWN (skip, not pass: no deployed tree on this " +
            "machine, so a consumer box never false-reds)"));
    const t = it.skipIf(!present);

    t(`${label} is deployed`, () => {
      assert.ok(existsSync(tree), `tree absent: ${tree}`);
    });

    const packs = present
      ? readdirSync(tree).sort().filter((p) => {
          if (p === "__pycache__" || p.startsWith(".")) return false;
          try {
            return statSync(join(tree, p)).isDirectory();
          } catch {
            return false;
          }
        })
      : [];
    for (const pack of packs) {
      if (norm(pack) === "comfyuimanager") {
        console.log(
          `  stand-down: ${label}/${pack} — its pin is the managed ` +
            "recipe's manager.pin (judged by provision verify in managed " +
            "mode), not a vendor gitlink or manifest row");
        continue;
      }
      const link = LINKS_BY_NORM.get(norm(pack));
      const row = ROWS.get(norm(pack));
      const pin = link?.[1] ?? row?.ref;
      const source = link !== undefined ? "vendor gitlink" : row !== undefined ? "manifest ref" : null;
      if (pin === undefined || pin === "" || source === null) {
        console.log(
          `  stand-down: ${label}/${pack} — no parent-repo pin (no vendor ` +
            "gitlink, no manifest row) — not judged");
        continue;
      }
      t(`${label}: ${pack} sits at ${source} ${pin.slice(0, 12)} and is clean`, () => {
        const dir = join(tree, pack);
        const head = spawnSync("git", ["-C", dir, "rev-parse", "HEAD"],
          { encoding: "utf8" });
        assert.equal(
          head.status, 0,
          `${label}/${pack}: not a verifiable git checkout ` +
            `(${(head.stderr ?? "").trim().slice(0, 180)}) — redeploy from ` +
            `the pin (git clone, then checkout ${pin.slice(0, 12)}); a ` +
            "hand-copied dir whose git identity dangles cannot be judged " +
            "and drifts silently (the audit 016 class)");
        assert.equal(
          (head.stdout ?? "").trim(), pin,
          `${label}/${pack}: HEAD ` +
            `${(head.stdout ?? "").trim().slice(0, 12)} != ${source} ` +
            `${pin.slice(0, 12)} — the repo's pack cures never reached ` +
            "this engine tree (audit 016 C4); redeploy the pack or " +
            "re-pin deliberately");
        const st = spawnSync(
          "git", ["-C", dir, "status", "--porcelain", "--untracked-files=no"],
          { encoding: "utf8" });
        assert.equal(st.status, 0,
          `${label}/${pack}: git status failed ` +
            `(${(st.stderr ?? "").trim().slice(0, 180)})`);
        const drift = (st.stdout ?? "").split("\n")
          .map((l) => l.trim())
          .filter((l) => l !== "")
          .filter((l) => !isBytecode(l));
        assert.deepEqual(
          drift, [],
          `${label}/${pack}: uncommitted source drift ` +
            `${JSON.stringify(drift)} — the working tree diverges from ` +
            "its checkout (commit, discard, or redeploy deliberately)");
      });
    }
  }
});
