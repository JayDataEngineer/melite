#!/usr/bin/env python3
"""gen_model_py.py — the models-as-python flip generator (one-shot, 2026-09-02).

Reads every plugins/engines/<engine>/models/<genre>/<id>/model.yaml (+
variants/*/variant.yaml) through the WIRE PARSERS themselves
(catalog._parse_model_yaml, editor_forms._parse_variant) and emits the
model.py class that reproduces the served row EXACTLY. Zero hand
transcription — the parity wall (tests/test_python_models.py +
tests/test_http_parity.py goldens) pins the result.

Resolver-side and provisioning data the text parsers never read
(patch defaults, quant artifacts, provisions blocks, lora_catalog)
come from PyYAML loads — they were DEAD WEIGHT in the yaml era and
now become live class data.

Run with --write to emit files; default is dry-run (prints plan).
After the flip: git rm the model.yaml + variants/ trees. The tool
stays in-tree as the transformation's provenance record.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(REPO, "py"))
sys.path.insert(0, os.path.join(REPO, "plugins", "web", "models_py"))

import catalog  # noqa: E402
import editor_forms  # noqa: E402

try:
    import yaml as pyyaml
except ImportError:
    pyyaml = None

ENGINES_ROOT = os.path.join(REPO, "plugins", "engines")

_CARD_BY_KIND = {"generate": "image-gen", "edit": "image-edit",
                 "music": "music"}


def _camel(mid):
    parts = re.split(r"[-_]", mid)
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    if not out or not out[0].isalpha():
        out = "M" + out
    return out


def _pystr(v):
    if v is None:
        return "None"
    if isinstance(v, bool):
        return "True" if v else "False"
    if isinstance(v, (int, float)):
        return repr(v)
    return repr(str(v))


def _pydict(d, indent="        "):
    if not d:
        return "{}"
    items = list(d.items())
    if len(items) <= 3:
        return "dict(" + ", ".join(
            "%s=%s" % (k if re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", k)
                       else repr(k), _pystr(v))
            for k, v in items) + ")"
    lines = ["dict("]
    for k, v in items:
        kw = k if re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", k) else repr(k)
        lines.append("%s    %s=%s," % (indent, kw, _pystr(v)))
    lines.append("%s)" % indent)
    return "\n".join(lines)


def _cell_name(vname, qid):
    return "%s%s" % (_camel(vname), _camel(str(qid) or "default"))


def load_model_unit(mdir):
    """The wire truth + the dead-weight data for one model dir."""
    text = open(os.path.join(mdir, "model.yaml"), encoding="utf-8",
                errors="surrogateescape").read()
    row = catalog._parse_model_yaml(text)
    raw = pyyaml.safe_load(text) or {} if pyyaml else {}
    variants = []
    vdir = os.path.join(mdir, "variants")
    if os.path.isdir(vdir):
        for name in sorted(os.listdir(vdir)):
            vyp = os.path.join(vdir, name, "variant.yaml")
            if not os.path.isfile(vyp):
                continue
            v = editor_forms._parse_variant(vyp)
            vraw = pyyaml.safe_load(open(vyp, encoding="utf-8",
                                         errors="surrogateescape").read()) \
                or {} if pyyaml else {}
            variants.append((name, v, vraw))
    return row, raw, variants


def gen_model_py(mdir, engine, genre):
    row, raw, variants = load_model_unit(mdir)
    mid = row["id"]
    if not mid:
        return None, None          # no family id — never served (catalog.c:479)
    cls_name = _camel(mid)

    L = []
    L.append("# %s — generated by tools/gen_model_py.py from the yaml" % mid)
    L.append("# cascade (2026-09-02 flip), then hand-edited since. The")
    L.append("# class IS the unit: family head → variants → quant cells;")
    L.append("# merged_defaults() walks the cascade. Parity pinned by")
    L.append("# tests/test_python_models.py + the http goldens.")
    L.append("#")
    L.append("# SSOT law: this file REPLACES model.yaml + variants/. A")
    L.append("# model.yaml reappearing next to it is a LOUD refusal.")
    L.append("")
    L.append("import os")
    L.append("import sys")
    L.append("")
    L.append("sys.path.insert(")
    L.append("    0, os.path.join(os.path.dirname(os.path.abspath(__file__)),")
    L.append('            "..", "..", "..", "..", "..", "web", "models_py"))')
    L.append("")
    L.append("from melite_models import Model, Variant, Cell, LoraRow")
    L.append("")
    L.append("")
    # cells per variant: one Cell class per quant tier in the variant's
    # quants block (first tier = the wire cell)
    for name, v, vraw in variants:
        qitems = _vraw_quants(vraw)
        for qid, q0 in qitems:
            q0 = q0 if isinstance(q0, dict) else {}
            L.append("class %s(Cell):" % _cell_name(name, qid))
            L.append("    quant = %r" % str(qid))
            if q0.get("label"):
                L.append("    label = %r" % str(q0["label"]))
            if q0.get("route"):
                L.append("    route = %r" % str(q0["route"]))
            vram = q0.get("vram_peak_gb") or q0.get("vram")
            if vram:
                L.append("    vram_peak_gb = %s" % _pystr(vram))
            src = q0.get("source") or {}
            if not isinstance(src, dict):
                src = {}
            url = q0.get("url") or src.get("url") or q0.get("source_url")
            if url:
                L.append("    source_url = %r" % str(url))
            prov = q0.get("provision") or {}
            if not isinstance(prov, dict):
                prov = {}
            size = q0.get("size_bytes") or q0.get("size")
            if size:
                L.append("    size_bytes = %s" % _pystr(size))
            hint_gb = prov.get("size_hint_gb") or q0.get("size_hint_gb")
            if hint_gb:
                L.append("    size_hint_gb = %s" % _pystr(hint_gb))
            sha = q0.get("sha256")
            if sha:
                L.append("    sha256 = %r" % str(sha))
            dest = prov.get("dest") or {}
            if not isinstance(dest, dict):
                dest = {}
            sub = q0.get("folder") or dest.get("sub") or q0.get("dest_sub")
            if sub:
                L.append("    dest_sub = %r" % str(sub).strip("/"))
            if q0.get("hide_from_dropdown"):
                L.append("    hide_from_dropdown = True")
            # WIRE overrides — the faithful bug: the C reads quant
            # attrs only until `label`, so the served route/vram are
            # whatever the parser saw BEFORE it. v[] IS that wire truth.
            wire_route = v["qroute"] or mid
            L.append("    wire_route = %r" % str(wire_route))
            L.append("    wire_vram = %s" % _pystr(v["vram"] or 0))
            # resolver defaults: quants-block defaults ∪ patch ∪ cell
            rd = {}
            if isinstance(q0.get("defaults"), dict):
                rd.update(q0["defaults"])
            patch = (vraw or {}).get("patch")
            if isinstance(patch, dict) and isinstance(
                    patch.get("defaults"), dict):
                rd.update(patch["defaults"])
            cellsec = q0.get("cell")
            if isinstance(cellsec, dict) and isinstance(
                    cellsec.get("defaults"), dict):
                rd.update(cellsec["defaults"])
            if rd:
                L.append("    resolver_defaults = %s" % _pydict(
                    rd, indent="        "))
            L.append("")
            L.append("")
    # variant classes
    for name, v, vraw in variants:
        vcls = _camel(name)
        L.append("class %s(Variant):" % vcls)
        L.append("    id = %r" % name)
        if v["label"]:
            L.append("    label = %r" % v["label"])
        if v["hint"]:
            L.append("    hint = %r" % v["hint"])
        L.append("    route = %r" % (v["route"] or mid))
        if isinstance((vraw or {}).get("order"), int):
            L.append("    order = %d" % vraw["order"])
        for qid, _q in _vraw_quants(vraw):
            L.append("    %s = %s" % (_camel(str(qid) or "cell"),
                                      _cell_name(name, qid)))
        L.append("")
        L.append("")
    # the model class
    L.append("class %s(Model):" % cls_name)
    # NAMING LAW: the dir name IS the id — the yaml's family.id aliases
    # (ace_step, minimax_music3, qwen3_tts…) collapse/desync the catalog;
    # post-flip every unit serves its dir id, matching the run door.
    L.append("    id = %r" % os.path.basename(mdir))
    if row.get("genre"):
        L.append("    genre = %r" % row["genre"])
    if row.get("label"):
        L.append("    label = %r" % row["label"])
    desc = row.get("description") or ""
    if desc:
        L.append("    description = %r" % desc)
    # enhance recipes (inference.yaml → python)
    ipath = os.path.join(mdir, "inference.yaml")
    if os.path.isfile(ipath):
        import sys as _sys
        _ef_dir = os.path.join(os.path.dirname(os.path.dirname(
            os.path.abspath(__file__))), "py")
        if _ef_dir not in _sys.path:
            _sys.path.insert(0, _ef_dir)
        import editor_forms as _ef
        prompt, lyrics = _ef._recipes(ipath)
        if prompt:
            L.append("    prompt_upscale = %r" % prompt)
        if lyrics:
            L.append("    lyrics_upscale = %r" % lyrics)
    if row.get("engine_plugin"):
        L.append("    engine = %r" % row["engine_plugin"])
    kind_marker = None
    if isinstance(raw, dict):
        kind_marker = raw.get("card")
        if isinstance(kind_marker, str) and kind_marker.strip():
            card_id = _CARD_BY_KIND.get(kind_marker.strip())
            if card_id:
                L.append("    card = %r  # the owning card surface" % card_id)
        if raw.get("form"):
            L.append("    form = %r" % str(raw["form"]))
        if raw.get("canvas_default"):
            L.append("    canvas_default = True")
    src = row.get("source") or {}
    if src.get("repo_id") is not None or src.get("filename") is not None \
            or (src.get("type") or "") != "":
        parts = ["%r: %r" % (k, src[k]) for k in ("type", "repo_id",
                                                  "filename")
                 if src.get(k) is not None]
        L.append("    source = {%s}" % ", ".join(parts))
    if row.get("defaults"):
        L.append("    defaults = %s" % _pydict(
            {k: catalog._json_value(v) for k, v in row["defaults"]},
            indent="        "))
    st = raw.get("studio") if isinstance(raw, dict) else None
    if isinstance(st, dict) and st.get("tenant"):
        L.append("    studio = dict(tenant=%r, owns_params=%s)" % (
            str(st["tenant"]),
            "True" if st.get("owns_params") else "False"))
    prov = _provisions(raw)
    if prov:
        L.append("    provisions = (")
        for p in prov:
            L.append("        dict(%s)," % ", ".join(
                "%s=%s" % (k, _pystr(p[k])) for k in sorted(p)))
        L.append("    )")
    loras = _lora_catalog(raw)
    if loras:
        L.append("    loras = (")
        for l in loras:
            L.append("        LoraRow(%s)," % ", ".join(
                "%s=%s" % (k, _pystr(l[k])) for k in sorted(l)))
        L.append("    )")
    for name, v, vraw in variants:
        L.append("    %s = %s" % (_camel(name), _camel(name)))
    L.append("")
    return "\n".join(L), mid


def _quants_items(qsec):
    """quants: may be a LIST of dicts or a DICT keyed by quant id
    (z-image shape). Normalize to ordered [(qid, qdict)]."""
    if isinstance(qsec, dict):
        return list(qsec.items())
    if isinstance(qsec, list):
        out = []
        for q in qsec:
            if isinstance(q, dict):
                out.append((str(q.get("id") or q.get("quant") or ""), q))
        return out
    return []


def _vraw_quants(vraw):
    """Ordered [(qid, qdict)] for a variant.yaml raw dict."""
    if not isinstance(vraw, dict):
        return []
    for holder in (vraw, vraw.get("variant"), vraw.get("cell")):
        if isinstance(holder, dict) and holder.get("quants") is not None:
            items = _quants_items(holder.get("quants"))
            if items:
                return items
    return []


def _provisions(raw):
    if not isinstance(raw, dict):
        return []
    fam = raw.get("family") if isinstance(raw.get("family"), dict) else {}
    prov = fam.get("provisions") or raw.get("provisions") or []
    out = []
    for p in prov:
        if isinstance(p, dict) and p.get("name") and p.get("url"):
            out.append({k: p[k] for k in
                        ("name", "url", "folder", "sha256", "size_bytes")
                        if p.get(k) is not None})
    return out


def _lora_catalog(raw):
    if not isinstance(raw, dict):
        return []
    fam = raw.get("family") if isinstance(raw.get("family"), dict) else {}
    cat = fam.get("lora_catalog") or raw.get("lora_catalog") or []
    out = []
    for l in cat:
        if not isinstance(l, dict) or not l.get("id"):
            continue
        out.append({k: l.get(k) for k in
                    ("id", "filename", "source_url", "label", "category",
                     "default_strength")
                    if l.get(k) is not None})
    return out


def main():
    write = "--write" in sys.argv
    only = None
    for a in sys.argv[1:]:
        if not a.startswith("-"):
            only = a
    n = 0
    for engine in sorted(os.listdir(ENGINES_ROOT)):
        models_root = os.path.join(ENGINES_ROOT, engine, "models")
        if not os.path.isdir(models_root):
            continue
        for genre in sorted(os.listdir(models_root)):
            gdir = os.path.join(models_root, genre)
            if not os.path.isdir(gdir):
                continue
            for mid in sorted(os.listdir(gdir)):
                mdir = os.path.join(gdir, mid)
                if not os.path.isfile(os.path.join(mdir, "model.yaml")):
                    continue
                if os.path.isfile(os.path.join(mdir, "model.py")):
                    continue
                if only and only != mid:
                    continue
                src, cid = gen_model_py(mdir, engine, genre)
                if src is None:
                    print("SKIP %s/%s (no family id — never served)"
                          % (engine, mid))
                    continue
                # self-check: the class must load and emit a parity row
                if write:
                    open(os.path.join(mdir, "model.py"), "w",
                         encoding="utf-8").write(src + "\n")
                    print("WROTE %s/%s/%s" % (engine, genre, cid))
                else:
                    print("would write %s/%s/%s (%d bytes)"
                          % (engine, genre, cid, len(src)))
                n += 1
    print("%d model unit(s) %s" % (n, "written" if write else "planned"))


if __name__ == "__main__":
    main()
